import { Array as Arr, Effect, String as Str } from "effect"
import type { Refused } from "#compiler/core/refusals.ts"
import {
	callText,
	type InsertAllComputedCase,
	insertAllComputedCases,
	insertAllComputedVerdict
} from "#test/support/agreement/insert-all-computed.ts"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { caseOwned, type Entry, type Program } from "#test/support/types/batch/batch.ts"

/**
 * The insertAllComputed program: every case of the insertAllComputed box (test/support/agreement/insert-all-computed.ts),
 * its call written with the typed builders, under the directive the type-test batch disarms exactly where the engine
 * refuses the case (insertAllComputedVerdict), the oracle. The directive names the refusal the types give the case's
 * fault: a relation the record names that lacks a computed field, a field no relation holds or one of another type,
 * each refused at its relation's key as a query member's head is; an ordered family's member by its own key; a record
 * of no field; and a row, at the top or nested, that states a computed field. Each case is a cell of the box.
 */

/** The cells of insertAllComputedBox, minted as a dictionary in its door
 * (test/types/changeset/insert-all-computed.dictionary.ts). */
export const insertAllComputedBoxItems: readonly [
	InsertAllComputedCase,
	...ReadonlyArray<InsertAllComputedCase>
] = insertAllComputedCases

/** The refusal the types give a case's fault, none for an admitted case. */
const refusalOf = (c: InsertAllComputedCase): Refused | undefined => {
	switch (c) {
		case "owner":
		case "tree":
		case "two":
			return undefined
		case "lacking":
		case "stranger":
			return "the query's head is not a fact of the relation"
		case "member":
			return "a sequence's member is written under its owner: nest it in order at the owner's count field"
		case "none":
			return "a computed insert computes at least one field: insert writes rows that state every field"
		case "type":
			return "a member's head writes each field at its type: an exact value re-enters a plain field only by Type.cast"
		case "stated":
		case "nested":
			return "a member fact is not a fact of the relation"
	}
}

/** A case's call, under the directive naming its refusal where the engine refuses it. */
const caseBlock = (c: InsertAllComputedCase, index: number): ReadonlyArray<string> => {
	const refused = insertAllComputedVerdict(c).kind === "refused"
	const refusal = refusalOf(c)
	const directive =
		refused && refusal !== undefined
			? `// @ts-expect-error -- refusal: ${refusal}\n`
			: refused
				? "// @ts-expect-error -- refused: the engine refuses a case the box names no refusal of\n"
				: ""
	return Str.split(
		`// ${c}
export const computed${index} = ChangeSet.empty(Packages)
${directive}${callText(c)}
`,
		"\n"
	)
}

/** The program's prelude (test/support/programs/insert-all-computed.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/insert-all-computed.ts"))

/** The program over a batch's cells, its imports read through its prelude as `entry` reaches it. */
export const insertAllComputedProgram = (
	cells: Arr.NonEmptyReadonlyArray<InsertAllComputedCase>,
	entry: Entry
): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/changeset/insert-all-computed.ts: insertAllComputed's records against the engine.",
		preludeFrom(prelude, entry),
		Arr.map(cells, (c, at) => ({ owner: caseOwned(at), lines: caseBlock(c, at) }))
	)
]
