import { Array as Arr } from "effect"
import { indices } from "#compiler/core/array.ts"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"

/**
 * The ChangeSet-member programs, one per op and member kind, each written over a schema of `relations` relations with
 * a ChangeSet of `members` members (members.test.ts). The schema is edullm pantry's import shape, which its replaceWrite
 * writes one member per relation of: relations R0 … of three fields each, a natural id and two texts of one type, Name,
 * keyed by its package and id, under no law. The ChangeSet writes the first `members` relations, one member each, by
 * one op: a delete, a put or an insert, each a call of its own, or one insertAll keyed by them. A member is a query, the
 * rows of its relation under a package parameter, as replaceWrite's are, or an array of the relation's facts.
 */
export type MemberShape = {
	readonly relations: number
	readonly members: number
	readonly op: MemberOp
	readonly kind: MemberKind
}

/** The ops a ChangeSet writes its members by: a call each, or one insertAll keyed by their relations. */
export type MemberOp = "delete" | "put" | "insert" | "insertAll"

/** What a member is: a query over the schema, or an array of facts. */
export type MemberKind = "query" | "array"

export const memberOps: ReadonlyArray<MemberOp> = ["delete", "put", "insert", "insertAll"]
export const memberKinds: ReadonlyArray<MemberKind> = ["query", "array"]

/** Member i of the ChangeSet, over relation i: a query of its rows under the package parameter, or its declared facts. */
const memberOf = (i: number, kind: MemberKind): string => {
	switch (kind) {
		case "query":
			return `query(S).rule((q) => {
	const stored = v(R${i}, "stored")
	return q.match(R${i}, stored).where(q.eq(stored.package, q.param("package", Name))).find(stored)
})`
		case "array":
			return `facts${i}`
	}
}

/** The ChangeSet's members: one call of the op for each, or one insertAll keyed by their relations. */
const membersOf = (shape: MemberShape): string => {
	switch (shape.op) {
		case "insertAll":
			return `\t.insertAll({\n${Arr.join(
				Arr.map(indices(shape.members), (i) => `\t\tR${i}: ${memberOf(i, shape.kind)}`),
				",\n"
			)}\n\t})`
		case "delete":
		case "put":
		case "insert":
			return Arr.join(
				Arr.map(indices(shape.members), (i) => `\t.${shape.op}(R${i}, ${memberOf(i, shape.kind)})`),
				"\n"
			)
	}
}

/** Each array member's facts, declared at the relation's Fact. */
const factsOf = (shape: MemberShape): string => {
	switch (shape.kind) {
		case "array":
			return Arr.join(
				Arr.map(
					indices(shape.members),
					(i) => `declare const facts${i}: ReadonlyArray<Fact<typeof R${i}>>\n`
				),
				""
			)
		case "query":
			return ""
	}
}

/** A complete program at `shape`, its imports read through the gates' prelude as `entries` reaches it. */
export const memberSource = (shape: MemberShape, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/changeset/budget/members.ts at ${jsonText(shape)}.`,
		entries,
		`export const Name = str.bytes(64, str.regex("^[a-z]+$"))
${Arr.join(
	Arr.map(
		indices(shape.relations),
		(i) =>
			`export const R${i} = relation("R${i}", { id: natural, label: Name, package: Name }, ["package", "id"])\n`
	),
	""
)}export const S = schema("S", [${Arr.join(
			Arr.map(indices(shape.relations), (i) => `R${i}`),
			", "
		)}], [])
${factsOf(shape)}export const change = ChangeSet.empty(S)
${membersOf(shape)}
`
	)
