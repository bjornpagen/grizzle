import { indices } from "@bjornpagen/grizzle-text/base/array"
import { Array as Arr } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { type GrowthDimension, equalSteps } from "#test/types/batch/measured.ts"

/**
 * The workload-width program (workloads.test.ts): a workload over a schema of many levels, each a level of the next, of
 * relations of distinct headings, as metis's composed roles read (its operator role's levels hold 2,374 relations of 35
 * schemas), checked at three widths, the widest past metis's. Its members are one of each kind a workload checks against
 * the programs of its levels (types/db/workload.ts ProgramAt): a query, a ChangeSet, a relation's primary key and a
 * candidate key, each read against every relation of every level.
 */

/**
 * The levels of every program, each a level of the next: metis's operator role reads 35 schemas. The levels are as
 * many at every width, so a wider program's levels each declare more relations, and its schema's chain of extensions
 * costs what a narrower one's does, its relations apart: what the widths tell apart is the relations a workload's
 * members are checked against.
 */
const levels = 30

/**
 * The relations of the narrowest program, a whole number of relations per level; the others hold two and three times
 * as many, the widest's 2,430 past metis's 2,374.
 */
const step = 27 * levels

/** Relation i: an id and a field of its own, so no two relations' records are one type. */
const relationOf = (i: number): string =>
	`export const R${i} = relation("R${i}", { id: pg.integer, f${i}: pg.integer }, ["id"])\n`

/** Level j of `width` relations: the relations it declares, over the level below it, the first over none, holding R2's key. */
const levelOf =
	(width: number) =>
	(j: number): string => {
		const names = Arr.join(
			Arr.map(indices(width), (i) => `R${j * width + i}`),
			", "
		)
		return j === 0
			? `export const L0 = schema("L0", [${names}], [K2])\n`
			: `export const L${j} = schema.extend([L${j - 1}], "L${j}", [${names}], [])\n`
	}

/** The program over `relations` relations, its imports read through the gates' prelude as `entries` reaches it. */
const workloadWidthSource = (relations: number, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/query/budget/workloads.ts at ${jsonText({ relations })}.`,
		entries,
		`${Arr.join(Arr.map(indices(relations), relationOf), "")}export const K2 = key(on(R2, "f2"))
${Arr.join(Arr.map(indices(levels), levelOf(relations / levels)), "")}export const read = query(L${levels - 1}).rule((r) => {
	const { id, f0 } = v(R0, "r")
	return r.match(R0, { id, f0 }).find({ id, f0 })
})
export const change = ChangeSet.empty(L${levels - 1}).insert(R0, [{ id: 1, f0: 1 }])
export const wide = workload(L${levels - 1}, { read, change, primary: R1, candidate: answered(K2) })
`
	)

/** The cells of workloadWidths, minted as a dictionary in its door (test/types/query/budget/workloads.dictionary.ts). */
export const workloadWidthsItems: readonly [GrowthDimension, ...ReadonlyArray<GrowthDimension>] = [
	{
		name: "a workload over levels of relations of distinct headings",
		steps: equalSteps(step),
		source: workloadWidthSource
	}
]
