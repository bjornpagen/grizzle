import { indices } from "@bjornpagen/grizzle-text/base/array"
import { assert, defined } from "@bjornpagen/testing/assert"
import { Array as Arr, Effect, Option } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { assertClean, type Measuring, measuredEach } from "#test/support/types/batch/measured.ts"

/**
 * The level programs (levels.test.ts), each a level built by a function over the level below it and read through
 * `ReturnType` of that function, as edullm's ledger reads its Delivery level (`DeliveryLevel = ReturnType<typeof
 * deliveryOf>`, sitting-programs.ts, TS2589 at 711 relations) and qti-database its assignment level. The base, built by
 * `baseOf`, holds `relations` relations R0 … of four fields, keyed by their id, each contained in the one before it. The
 * level, built by `levelOf(base: BaseLevel)`, reads a chain of eight queries over queries, q0 over R0 and R1, each
 * further one over the one before it, and states `derived` derived relations, D0 …, each a query over the chain's last
 * and a base relation (round them), with a check over each, as Delivery's derived relations read queries over queries
 * over the ledger. Where `read` is "returnType", the program types the level by `Level = ReturnType<typeof levelOf>` and
 * the value it installs at that type; where it is "value", by the value's own type, `typeof installed`. Either way a
 * builder over the level, `programsOf(level: Level)`, reads its first derived relation in a query.
 */
type LevelShape = {
	readonly relations: number
	readonly derived: number
	readonly read: "returnType" | "value"
}

/** The chain of queries over queries every level reads: q0 over the base, each further one over the one before it. */
const chainLength = 8

/** The base's relations, each contained in the one before it. */
const baseOf = (relations: number): string => `export const baseOf = () => {
${Arr.join(
	Arr.map(
		indices(relations),
		(i) =>
			`\tconst R${i} = relation("R${i}", { id: Id, parent: Id, n: natural, label: Label }, ["id"])`
	),
	"\n"
)}
	return schema("Base", [${Arr.join(
		Arr.map(indices(relations), (i) => `R${i}`),
		", "
	)}], [${Arr.join(
		Arr.map(indices(relations - 1), (i) => `contained(on(R${i + 1}, "parent"), on(R${i}, "id"))`),
		", "
	)}])
}
export type BaseLevel = ReturnType<typeof baseOf>
`

/** Query k of the chain: q0 over R0 and R1, each further one over the one before it and R0. */
const chainQuery = (k: number): string =>
	k === 0
		? `\tconst q0 = query(base).rule((r) => {
		const { id, parent } = v(f.R0, "a")
		const { n } = v(f.R1, "b")
		return r.match(f.R0, { id, parent }).match(f.R1, { id: parent, n }).find({ id, n })
	})`
		: `\tconst q${k} = query(base).rule((r) => {
		const { id, n } = v(q${k - 1}, "q")
		const { label } = v(f.R0, "a")
		return r.match(q${k - 1}, { id, n }).match(f.R0, { id, label }).find({ id, n })
	})`

/** Derived relation d: the chain's last query beside base relation d (round them). */
const derivedRelation = (
	d: number,
	relations: number
): string => `\tconst D${d} = derived("D${d}", query(base).rule((r) => {
		const { id, n } = v(q${chainLength - 1}, "q")
		const { label } = v(f.R${d % relations}, "r")
		return r.match(q${chainLength - 1}, { id, n }).match(f.R${d % relations}, { id, label }).find({ id, n, label })
	}))`

/** The level over the base: the chain, the derived relations, a check over each, and the extension listing them. */
const levelOf = (shape: LevelShape): string => `export const levelOf = (base: BaseLevel) => {
	const f = base.relations
${Arr.join(Arr.map(indices(chainLength), chainQuery), "\n")}
${Arr.join(
	Arr.map(indices(shape.derived), (d) => derivedRelation(d, shape.relations)),
	"\n"
)}
	const relations = [${Arr.join(
		Arr.map(indices(shape.derived), (d) => `D${d}`),
		", "
	)}] as const
	const laws = [${Arr.join(
		Arr.map(indices(shape.derived), (d) => `check("D${d}_n", D${d}, (x) => x.ge(x.n, 0n))`),
		", "
	)}] as const
	return schema.extend([base], "Level", [...relations], [...laws])
}
`

/** How the program types the level: by ReturnType of the function that builds it, or by the value it installs. */
const readOf = (shape: LevelShape): string =>
	shape.read === "returnType"
		? `export type Level = ReturnType<typeof levelOf>
export const installed: Level = levelOf(baseOf())
`
		: `export const installed = levelOf(baseOf())
export type Level = typeof installed
`

/** A complete program at `shape`, its imports read through the gates' prelude as `entries` reaches it. */
const levelSource = (shape: LevelShape, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/schema/budget/levels.ts at ${jsonText(shape)}.`,
		entries,
		`const Label = str.regex("^[a-z]{1,32}$")
${baseOf(shape.relations)}${levelOf(shape)}${readOf(shape)}export const programsOf = (level: Level) => {
	const f = level.relations
	return query(level).rule((r) => {
		const { id, n } = v(f.D0, "d")
		return r.match(f.D0, { id, n }).find({ id, n })
	})
}
`
	)

/** The base sizes and derived counts the level gate measures a level at, each the next twice the one before. */
export interface LevelCorners {
	readonly name: string
	readonly relations: readonly [number, number]
	readonly derived: readonly [number, number]
}

/** The cells of levelCorners, minted as a dictionary in its door (levels.dictionary.ts): past Delivery's size. */
export const levelCornersItems: Arr.NonEmptyReadonlyArray<LevelCorners> = [
	{
		name: "a level of 50 and 100 derived relations over 500 and 1,000 base relations",
		relations: [500, 1000],
		derived: [50, 100]
	}
]

/**
 * A level's cost at each corner of the base sizes and derived counts, read as its value's type and through ReturnType,
 * and the laws over them: a further base relation costs as many instantiations under the larger level as under the
 * smaller, I(2b, 2d) − I(b, 2d) = I(2b, d) − I(b, d), so the level grows with its base and with its derived relations
 * apart, never with their product; and so does what the ReturnType read costs beyond the value's type. Every program
 * typechecks with no diagnostic, the largest, a level of 100 derived relations over 1,000 base relations, among them.
 */
export const levelCost = (at: Measuring, corners: LevelCorners) =>
	Effect.gen(function* () {
		const shapes = Arr.flatMap(corners.relations, (relations) =>
			Arr.flatMap(corners.derived, (derived) =>
				Arr.map(["returnType", "value"] as const, (read) => ({ relations, derived, read }))
			)
		)
		const measured = yield* measuredEach(
			at,
			Arr.map(shapes, (shape, index) => ({
				size: index,
				source: (entries: PreludeAt) => levelSource(shape, entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, `${corners.name}: ${jsonText(defined(shapes[m.size], "a measured shape"))}`)
		}
		const instantiationsOf = (relations: number, derived: number, read: LevelShape["read"]) =>
			defined(
				Option.getOrUndefined(
					Arr.findFirst(measured, (m) => {
						const shape = shapes[m.size]
						return (
							shape?.relations === relations && shape.derived === derived && shape.read === read
						)
					})
				),
				`${corners.name} is measured at ${relations} relations and ${derived} derived, ${read}`
			).instantiations
		const [b, b2] = corners.relations
		const [d, d2] = corners.derived
		const lawOf = (what: string, cost: (relations: number, derived: number) => number) =>
			assert.equal(
				cost(b2, d2) - cost(b, d2),
				cost(b2, d) - cost(b, d),
				`${corners.name}: ${what} adds as much for a further base relation under ${d2} derived relations as under ${d} (${cost(b, d)} at ${b} and ${d}, ${cost(b2, d)} at ${b2} and ${d}, ${cost(b, d2)} at ${b} and ${d2}, ${cost(b2, d2)} at ${b2} and ${d2})`
			)
		lawOf("the level, read as its value's type,", (relations, derived) =>
			instantiationsOf(relations, derived, "value")
		)
		lawOf(
			"the ReturnType read, beyond the value's type,",
			(relations, derived) =>
				instantiationsOf(relations, derived, "returnType") -
				instantiationsOf(relations, derived, "value")
		)
	})
