/**
 * The runtime file of one declared schema's snapshot, in its migrations directory: what an application imports for
 * DbLayer.make, the members a layer reads (ServedSnapshot) and the fingerprint of the whole snapshot.
 */
export const snapshotFileName = "snapshot.json"

/**
 * The migration file of one declared schema's snapshot, beside snapshot.json: every member of the snapshot that file does
 * not hold, which only `grizzle generate`, check, drift and migrate read.
 */
export const manifestFileName = "manifest.json"

/**
 * The texts of a snapshot's two files as `grizzle generate` writes them (build.ts writeSnapshot): snapshot.json and
 * manifest.json, which hold each member of the snapshot once between them, under the one fingerprint snapshot.json
 * records over both.
 */
export interface SnapshotFiles {
	readonly snapshot: string
	readonly manifest: string
}

/** How a stored relation's field is written, as the snapshot records it: by its caller; by its identity sequence
 * (serial); generated by PostgreSQL from its row, with the digest of its generation expression's canonical text; drawn
 * by grizzle from the nested arrays (a family's index or count, a tree's start or end), with the digest of what draws
 * it; or accumulated by grizzle on the host, with the digest of its start value and of what fills it (a fold, or a
 * containment riding a family's axis). What fills a field is its role and every law that says what it holds
 * (laws/model/fillers.ts Filler), so a changed expression, start, family, fold or copy changes the record, and the
 * migration draws the field again; a declaration that only renames what fills it changes nothing (deploy/diff/declared.ts). */
export type SnapshotWriting =
	| "caller"
	| "serial"
	| { readonly generated: string }
	| { readonly drawn: string }
	| { readonly accumulated: string }

/** A field of a stored relation as the snapshot records it: its installed column, the digest of its canonical
 * ScalarType (which is its identity) with every roster named by its name alone, and how it is written. A roster's
 * handles are no part of a field's recorded type: they are the roster's codes, which the roster's own record holds, so
 * a roster's growth changes no field. */
export interface SnapshotField {
	readonly name: string
	readonly column: ColumnIdent
	readonly type: string
	readonly writing: SnapshotWriting
}

interface SnapshotRelationOf<K extends "relation" | "closed" | "derived"> {
	readonly kind: K
	/** The table, roster domain or materialized view identifier. */
	readonly ident: RelationIdent
	readonly mutable: boolean
	/** The schema level that declares it, and a derived relation's level over what it reads. */
	readonly level: number
}

/** A stored relation's heading in declared order, its primary key, and the attribute numbers its table has used: one
 * per column it was created with and per column added since, its dropped ones included, which PostgreSQL never reuses
 * and counts against tableMaxColumns. */
interface SnapshotHeading {
	readonly fields: ReadonlyArray<SnapshotField>
	readonly primaryKey: ReadonlyArray<string>
	readonly attnums: number
}

/**
 * A relation of the snapshot's theory, by kind: a stored relation with its heading; a roster, by its domain, with its
 * codes; a derived relation, whose fields are its view's columns, which its materialized view object records.
 *
 * A roster's codes are code c at position c, each the live handle it names or the hole a removed handle left, and their
 * length is the next code, so no separate counter can disagree with them. A closed relation of any other arity has no
 * record: nothing is installed under its name, and its rows reach the database only as the content-addressed constants
 * and the migration's checks the manifest and the laws record.
 */
export type SnapshotRelation =
	| (SnapshotRelationOf<"relation"> & SnapshotHeading)
	| (SnapshotRelationOf<"closed"> & { readonly codes: RosterCodes })
	| SnapshotRelationOf<"derived">

/** A law of the snapshot's theory by how it is enforced: natively, by its shape alone; a law that reads closed
 * relations only, once by the migration that installs them, with the digest of the violation query that migration
 * runs, which a change of the law or of the rows it reads changes; or a rule over a query, by its triggers, with the
 * digest of the violation query the migration that adds or changes it runs. */
export type SnapshotLaw =
	| { readonly kind: "native"; readonly shape: string }
	| { readonly kind: "migration" | "trigger"; readonly shape: string; readonly digest: string }

export interface SnapshotTheory {
	/** The owned schema's fingerprint. */
	readonly schema: SchemaFingerprint
	readonly relations: Readonly<Record<string, SnapshotRelation>>
	readonly laws: Readonly<Record<string, SnapshotLaw>>
}

/**
 * A level of the installation as the snapshot records it, root first: its declared name, the PostgreSQL schema its
 * relations live in, its own fingerprint, the owned fingerprint of the schema it tops, by which a login over it is
 * served (DbLayer.make admits a login over any level the snapshot records), and each law it states that the levels
 * below it do not, by its law identity, as an outcome names it. A Db over a lower level holds none of a higher level's
 * code, so it reports a refusal by one of these as the law `above` names (types/changeset Law); the root states none
 * above anything, and records the laws of its own alike.
 */
export interface SnapshotLevel {
	readonly name: string
	readonly schema: string
	readonly fingerprint: SchemaFingerprint
	readonly laws: ReadonlyArray<DescribedLaw>
}

/** A login of an installation as the snapshot records it, under its declared name: its PostgreSQL role, whose name
 * the naming door derives from the installation's and the login's (core/identity.ts identity.login). A declared rename
 * of the login (deploy/diff/plan.ts Declarations) renames this role in place, so the record names one role across it. */
export interface SnapshotLogin {
	readonly role: string
}

/** The canonical schema snapshot: the canonical serialization of what an installation is. It holds a summary of the
 * CheckedTheory (its relations, their fields and mutability, its rosters' codes, and its laws), the installation manifest
 * with every object's DDL and justification (a law identity, the workload's access, or the enforcement of a
 * declaration), the constraint-to-law map, each login by its declared name with its PostgreSQL role, each login's
 * workload programs' access (ProgramAccess: the paths and
 * statistics each program reads through, by login and program name) and the access requests they make. The application
 * commits it beside its code as `migrations/<schema>/snapshot.json`, one per declared schema; the next migration is
 * drafted from it, the current schema and the current workloads, never from the live catalog, and DbLayer.make and
 * `grizzle check` compare the workloads' access with it, naming a program whose access moved. A program edit that moves
 * no path leaves it unchanged. Its history is each roster's codes and each table's attribute numbers: everything else in
 * it is derived from the current schema and those codes alone, so a fresh installation and a migrated one are the same
 * snapshot exactly when no roster has a hole or a renamed handle and no table a dropped column.
 * The fingerprint is SHA-256, in the domain `snapshot`, over the canonical text of everything else, so it covers the
 * manifest, the workload access and the rosters' codes as well as the owned schema's own fingerprint (`theory.schema`):
 * a program whose access moves, or a roster whose handle is removed, is a new snapshot. It is what a folder's meta.json and the migrations ledger record as the source and
 * target of each migration and what every Db's prologue guards. The committed snapshot is two files (SnapshotFiles):
 * snapshot.json, what an application reads, and manifest.json, the rest, which together hold the one canonical value
 * the fingerprint digests. */
export interface DeploySnapshot extends Snapshot<SqlStatement> {
	readonly fingerprint: SchemaFingerprint
	/**
	 * The installation's root's declared name and PostgreSQL schema, which name the installation: its migrations
	 * directory, its ledger's schema and its empty snapshot's fingerprint, whatever levels stand above the root.
	 */
	readonly schemaName: string
	readonly schema: string
	/** The installed levels, root first; none before the first migration. */
	readonly levels: ReadonlyArray<SnapshotLevel>
	readonly theory: SnapshotTheory
	readonly manifest: InstallationManifest<SqlStatement>
	readonly constraintToLaw: ConstraintLaws
	/** Each login the installation creates, by its declared name. */
	readonly logins: Readonly<Record<string, SnapshotLogin>>
	readonly workload: WorkloadAccess
	/**
	 * The installation's live plan (live/notify.ts LivePlan): every stored relation a login's read program reads, each with
	 * every field some read program routes a change of it by, and every materialized derived relation one reads
	 * (program/workload/compile.ts WorkloadPlan live). snapshot.json holds it, under the fingerprint: what the
	 * installation signals a change of is part of what it is.
	 */
	readonly live: LivePlan
}

/**
 * What an application's DbLayer and the Dbs it serves read of the committed snapshot, parsed once where the layer is
 * built from snapshot.json alone (served.ts servedSnapshot): the recorded fingerprint, which every Db's prologue guards
 * the database's ledger with; every level's PostgreSQL schema, the levels above the one the layer serves with the laws
 * each states, and the constraint-to-law map, which name a refusal by a law of a level above a Db's own
 * (witness/keylaw.ts lawsAbove); the installation's codes (codebookOf), its rosters' history, which no schema alone
 * determines; and the installation's derived runtime facts (SnapshotDerived). Nothing else of a snapshot reaches an application: `grizzle generate`, check, drift and migrate read the
 * whole DeploySnapshot, from both its files.
 */
export interface ServedSnapshot {
	readonly fingerprint: SchemaFingerprint
	/** Every level's PostgreSQL schema, root first. */
	readonly schemas: ReadonlyArray<string>
	/** Every level's recorded fingerprint, root first, which the layer owns its base's levels under, by position. */
	readonly fingerprints: ReadonlyArray<SchemaFingerprint>
	/** The levels above the one the layer serves, root first, each by its name with the laws it states. */
	readonly above: ReadonlyArray<Pick<SnapshotLevel, "name" | "laws">>
	readonly constraintToLaw: ConstraintLaws
	readonly codes: Codebook
	/** The installation's derived runtime facts, as snapshot.json records them beside its content. */
	readonly derived: SnapshotDerived
}

/**
 * The derived facts a level's artifacts compile under besides its codes (build.ts derivedFacts), which a login over a
 * lower level reads before the installation is compiled as well as after (adapter/served/login.ts artifactsUnder).
 */
export interface CompileFacts {
	/**
	 * Each closed relation's constants as readers address them, by the relation's declared name, rosters aside: every
	 * function by its identifier, its key's layout and its payload's radices under the installation's codes
	 * (physical/ddl/constants.ts NamedClosed). generate plans them from the relations' rows, packing each string of
	 * cells to name it by its digest; DbLayer.make reads them here and packs nothing.
	 */
	readonly closed: ClosedNames
	/**
	 * The foreign key graph's strongly connected components of more than one relation, names in code point order, which
	 * a layer planning only a slice reads for its deferral (laws/model/model.ts FkCycles). generate plans them from every
	 * law; DbLayer.make reads them here and plans no law its slice does not name.
	 */
	readonly fkCycles: FkCycles
	/**
	 * The parts whose fixed targets take the shared reference (laws/model/plan.ts ReferenceChoice), which a layer planning
	 * only a slice reads for each reference it plans. generate chooses them over every law; DbLayer.make reads them here
	 * and chooses none.
	 */
	readonly references: ReferenceChoice
	/**
	 * Each structural text domain the installation's stored fields declare, by its pattern language's key, with the digest
	 * that names it (physical/ddl/domains.ts TextDomainNames), which every compile names a refined text's domain by
	 * whatever relations its slice reads. generate plans them from every stored field; DbLayer.make reads them here and
	 * types no field its slice does not read.
	 */
	readonly textDomains: TextDomainNames
}

/**
 * What a law column holds, as the law model planned it (laws/model/plan.ts LawColumnPlan), by the field whose values it
 * holds: a term's, its relation's own field where the law's selection holds; a constant's, the value a target fixes its
 * field to; a family's drawn index's or count's; or the predecessor of a drawn index of its family.
 */
export type LawColumnHolds =
	| { readonly kind: "term"; readonly field: string }
	| { readonly kind: "constant"; readonly target: string; readonly field: string }
	| { readonly kind: "drawn"; readonly field: string }
	| { readonly kind: "predecessor"; readonly field: string }

/**
 * One key column of an index, in the index's key order: a field of the relation, by its declared name, or a law column
 * the law model adds to the relation, by what it holds and the laws the manifest records it for; with its direction, a
 * B-tree's ascending or descending, or none for an index that orders nothing (GiST, HNSW, hash).
 */
export type IndexKeyColumn = { readonly direction: "asc" | "desc" | "none" } & (
	| { readonly kind: "field"; readonly field: string }
	| {
			readonly kind: "law"
			readonly holds: LawColumnHolds
			readonly laws: ReadonlyArray<LawId>
	  }
)

/**
 * An index the installation holds: its key columns in order (IndexKeyColumn), and the reasons its manifest records for it
 * (ir/products.ts PhysicalReason).
 */
export interface SnapshotIndex {
	readonly columns: NonEmptyReadonlyArray<IndexKeyColumn>
	readonly reasons: ReadonlyArray<PhysicalReason>
}

/**
 * An installed table or materialized view as a plan names it: the declared name of the relation it stores, a stored
 * relation's or a materialized derived relation's, and each index PostgreSQL holds on it, by the index's name
 * (SnapshotIndex). A primary key's, a unique key's and an exclusion constraint's index is named by its constraint,
 * which PostgreSQL names the index after, and a created index by its CREATE INDEX.
 */
export interface SnapshotTable {
	readonly relation: string
	readonly indexes: Readonly<Record<string, SnapshotIndex>>
}

/**
 * Tables and materialized views of an installation as EXPLAIN (VERBOSE) names them, by their PostgreSQL schema, then by
 * their own name (SnapshotTable).
 */
export type SnapshotTables = Readonly<Record<string, Readonly<Record<string, SnapshotTable>>>>

/**
 * The facts snapshot.json records beside the snapshot's content for DbLayer.make, derived from the installation's
 * compile and no part of the content its fingerprint digests, so they change no fingerprint and no database's ledger:
 * `grizzle generate` writes them from the compile it drafts from (build.ts derivedOf), and the served compile reads them
 * instead of compiling them again: the facts a level's artifacts compile under (CompileFacts), and every table and
 * materialized view the installation installs with its indexes (`tables`), which a login's served file cuts to its
 * own statements' (adapter/served/project.ts) and an explain names a plan's relations and indexes by.
 */
export interface SnapshotDerived extends CompileFacts {
	readonly tables: SnapshotTables
}

/** A snapshot without its fingerprint: what the fingerprint is computed over. */
export type SnapshotContent = Omit<DeploySnapshot, "fingerprint">
