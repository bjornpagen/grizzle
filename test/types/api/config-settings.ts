import { Array as Arr, Effect } from "effect"
import { configSettings } from "#cli/errors.ts"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { batchOwned, caseOwned, type Entry, type Program } from "#test/support/types/batch/batch.ts"

/**
 * The configuration-settings program: defineConfig given every setting a configuration has, each one left out, and a
 * setting no configuration has beside them all, each call one line of a program the type batch checks.
 *
 * The oracle is the command line's loader as its roster states it (cli/errors.ts configSettings, cli/config.ts
 * onlyKeys): a configuration holds every setting of the roster, each required, and none else. A call the loader would
 * refuse is refused at its line, a setting left out or a setting it has no name for, qti-pie's `contracts` (deleted at
 * PIN 3) among them.
 */

/** A setting of the loader's roster (cli/errors.ts configSettings). */
type Setting = (typeof configSettings)[number]

/** Each setting's value in the program's configuration, over the program's header. */
const valueOf: { readonly [S in Setting]: string } = {
	schemas: "[Root]",
	logins: "[]",
	migrations: '"migrations"',
	rolePrefixBytes: "0",
	connection: "() => connection"
}

/** A setting no configuration has, and its value: the setting the deleted contracts were declared under. */
const stranger = ["contracts", "[]"] as const

/** A cell: the configuration with every setting, one left out, or every setting and the stranger beside them. */
type Cell = "every setting" | `without ${Setting}` | "every setting and a stranger"

/** The cells of configSettingsBox, minted as a dictionary in its door (config-settings.dictionary.ts). */
export const configSettingsBoxItems: Arr.NonEmptyReadonlyArray<Cell> = [
	"every setting",
	...Arr.map(configSettings, (s): Cell => `without ${s}`),
	"every setting and a stranger"
]

/** A cell's configuration: its settings and their values, in the roster's order, the stranger's last. */
const settingsOf = (cell: Cell): ReadonlyArray<readonly [string, string]> => {
	const every = Arr.map(configSettings, (s) => [s, valueOf[s]] as const)
	if (cell === "every setting") {
		return every
	}
	if (cell === "every setting and a stranger") {
		return [...every, stranger]
	}
	return Arr.filter(every, ([s]) => `without ${s}` !== cell)
}

/** Whether the loader admits a cell's configuration: every setting of its roster and no other. */
const admitted = (cell: Cell): boolean => {
	const keys: ReadonlyArray<string> = Arr.map(settingsOf(cell), ([s]) => s)
	const roster: ReadonlyArray<string> = configSettings
	return Arr.every(roster, (s) => keys.includes(s)) && Arr.every(keys, (k) => roster.includes(k))
}

/** The program's prelude (test/support/programs/config-settings.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/config-settings.ts"))

/** The schema every configuration installs and the connection it names. */
const configHeader: ReadonlyArray<string> = [
	'export const Item = relation("Item", { id: int4 }, ["id"])',
	'export const Root = schema("Root", [Item], [])',
	"export declare const connection: MigrationConnectionConfig",
	""
]

/** A cell's lines: defineConfig of its configuration on one line, refused at it where the loader refuses it. */
const cellLines = (cell: Cell, at: number): ReadonlyArray<string> => [
	`// ${cell}`,
	...(admitted(cell) ? [] : ["// @ts-expect-error -- refused: the loader refuses it"]),
	`export const c${at} = defineConfig({ ${Arr.join(
		Arr.map(settingsOf(cell), ([s, v]) => `${s}: ${v}`),
		", "
	)} })`
]

/** The program over a batch's cells, its imports read through its prelude as `entry` reaches it. */
export const configSettingsProgram = (
	cells: Arr.NonEmptyReadonlyArray<Cell>,
	entry: Entry
): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/api/config-settings.ts: defineConfig's settings against the loader's roster.",
		preludeFrom(prelude, entry),
		[
			{ owner: batchOwned, lines: configHeader },
			...Arr.map(cells, (cell, at) => ({ owner: caseOwned(at), lines: cellLines(cell, at) }))
		]
	)
]
