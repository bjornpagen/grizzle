import { regex } from "arkregex"
import { Array as Arr, Option } from "effect"

/**
 * The source of packages/engine/src/scalar/regex/categories.generated.ts: every code point's Unicode General_Category,
 * as the running Node's regular expressions read it (`\p{General_Category=…}` under the `u` flag), written as the runs
 * the categories cut the code space into. A run is a category's two-letter value and its length, so the table states
 * a partition of U+0000 to U+10FFFF, each code point in exactly one category, which no list per category could hold
 * apart from its neighbours'. XML Schema's category escapes read the version Node ships, as its Appendix F invites
 * ("the version of the Unicode database in use"), so a Node that ships another Unicode regenerates the table, and the
 * unit test of the XSD reader holds the committed table to this one, run by run.
 */

/** The two-letter General_Category values, which partition the code space (Unicode §4.5, Table 4-4). */
const generalCategories = [
	"Lu",
	"Ll",
	"Lt",
	"Lm",
	"Lo",
	"Mn",
	"Mc",
	"Me",
	"Nd",
	"Nl",
	"No",
	"Pc",
	"Pd",
	"Ps",
	"Pe",
	"Pi",
	"Pf",
	"Po",
	"Sm",
	"Sc",
	"Sk",
	"So",
	"Zs",
	"Zl",
	"Zp",
	"Cc",
	"Cf",
	"Cs",
	"Co",
	"Cn"
] as const

/** The last code point. */
const lastCodePoint = 0x10ffff

/** The category of each code point, read by the running Node's regular expressions. */
const categoryOf = (): ((point: number) => number) => {
	const tests = Arr.map(generalCategories, (g) => regex.as(`^\\p{General_Category=${g}}$`, "u"))
	return (point) => {
		const text = String.fromCodePoint(point)
		return Option.getOrThrowWith(
			Arr.findFirstIndex(tests, (t) => t.test(text)),
			() => new Error(`U+${point.toString(16)} in no General_Category of the partition`)
		)
	}
}

/** The Unicode version the running Node's regular expressions read. */
const unicodeVersion = (): string =>
	Option.getOrThrowWith(
		Option.fromNullishOr(process.versions["unicode"]),
		() => new Error("the running Node reports no Unicode version")
	)

/**
 * The runs of the partition as one text: each run its category's index in generalCategories as one letter (a to z,
 * then A to D) and its length in base 36, the runs joined by commas, in code point order from U+0000.
 */
export const runsOfRunningNode = (): string => {
	const of = categoryOf()
	const runs: Array<string> = []
	let start = 0
	let current = of(0)
	const letter = (index: number): string =>
		String.fromCharCode(index < 26 ? 0x61 + index : 0x41 + index - 26)
	for (let point = 1; point <= lastCodePoint + 1; point++) {
		const next = point > lastCodePoint ? -1 : of(point)
		if (next === current) {
			continue
		}
		runs.push(`${letter(current)}${(point - start).toString(36)}`)
		start = point
		current = next
	}
	return Arr.join(runs, ",")
}

/** The module scalar/regex/categories.generated.ts holds. */
export const categoriesSource = (): string =>
	Arr.join(
		[
			"/**",
			" * Every code point's Unicode General_Category, generated by `node scripts/gen/unicode/main.ts` from the running",
			` * Node's regular expressions (Unicode ${unicodeVersion()}): the runs the categories cut U+0000 to U+10FFFF into,`,
			" * each its category's index in generalCategories as one letter (a to z, then A to D) and its length in base 36,",
			" * joined by commas in code point order. Do not edit: regenerate it.",
			" */",
			"",
			"/** The two-letter General_Category values, in the order a run's letter indexes them. */",
			"export const generalCategories = [",
			Arr.join(
				Arr.map(generalCategories, (g) => `\t"${g}"`),
				",\n"
			),
			"] as const",
			"",
			"/** The runs (see the header). */",
			"export const categoryRuns =",
			`\t"${runsOfRunningNode()}"`,
			""
		],
		"\n"
	)
