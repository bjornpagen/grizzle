import { Array as Arr, Effect } from "effect"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { batchOwned, caseOwned, type Entry, type Program } from "#test/support/types/batch/batch.ts"

/**
 * The public-Result program: the box of every answer a public reader gives that can refuse with a value, each printed
 * as one line of a program the type batch checks: codecText's text, rowEvaluator's compile, an admission, a generated
 * value, a check's verdict and a selection, insertPreview's compile and a preview, factsDecoder's compile and a
 * decode, and indexesOf's index map.
 *
 * The oracle: grizzle answers one Result, Effect's. Each answer is Effect's Result of its own success and failure
 * exactly, and neither shape of the engine's own Result (core/result.ts), Ok or Err, is assignable to it, so a caller
 * that reads one answer by `Result.isSuccess` reads them all, and no answer a caller reads is the engine's `{ ok }`.
 * The schema the answers are read over, a relation with a generated field and a row check, is the batch's own.
 */

/** Each answer of the box, by the type the program reads it as over the batch's schema, Accounts. */
const answers = {
	"codecText's text": "ReturnType<typeof unitsText>",
	"rowEvaluator's compile": "typeof evaluator",
	"an admission": "ReturnType<RowEvaluator<typeof Accounts>['admit']>",
	"a generated value": "RowEvaluation<typeof Accounts, typeof Account>['generated']['copied']",
	"a check's verdict": "RowEvaluation<typeof Accounts, typeof Account>['checks']['Positive']",
	"a selection": "RowEvaluation<typeof Accounts, typeof Account>['selected']",
	"insertPreview's compile": "typeof preview",
	"a preview": "ReturnType<InsertPreview<typeof Accounts>>",
	"factsDecoder's compile": "typeof decoder",
	"a decode": "ReturnType<FactsDecoder<typeof Accounts>['decode']>",
	"indexesOf's index map": "ReturnType<typeof indexesOf>"
} as const

type Answer = keyof typeof answers

/** The cells of resultsBox, minted as a dictionary in its door (test/types/api/results.dictionary.ts). */
export const resultsBoxItems: Arr.NonEmptyReadonlyArray<Answer> = [
	"codecText's text",
	"rowEvaluator's compile",
	"an admission",
	"a generated value",
	"a check's verdict",
	"a selection",
	"insertPreview's compile",
	"a preview",
	"factsDecoder's compile",
	"a decode",
	"indexesOf's index map"
]

/** The program's prelude (test/support/programs/results.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/results.ts"))

/** The schema every answer is read over, and the verdict each cell states of its answer, the batch's own. */
const resultsHeader: ReadonlyArray<string> = [
	'export const Account = relation.generated("Account", { id: Id, units: int8 }, ["id"], (r) => ({',
	"\tcopied: generated(int8, r.units)",
	"}))",
	'export const Accounts = schema("Accounts", [Account], [check("Positive", Account, (a) => a.gt(a.units, 0n))])',
	"export const unitsText = codecText(Account.fields.units)",
	"export const evaluator = rowEvaluator(Accounts)",
	"export const preview = insertPreview(Accounts)",
	"export const decoder = factsDecoder(Accounts)",
	"export type Equals<A, B> = (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false",
	"export type Expect<T extends true> = T",
	"/** Whether T is Effect's Result of its own success and failure, exactly. */",
	"export type IsPublic<T> = [T] extends [Result.Result<infer A, infer E>] ? Equals<T, Result.Result<A, E>> : false",
	"/** Whether a shape of the engine's own Result, Ok or Err, is assignable to T. */",
	"export type TakesEngine<T> = [Ok<never>] extends [T] ? true : [Err<never>] extends [T] ? true : false",
	"/** An answer's verdict: Effect's Result, and no engine shape. */",
	"export type Verdict<T> = [IsPublic<T>, TakesEngine<T>]",
	""
]

/** The program over a batch's cells, its imports read through its prelude as `entry` reaches it. */
export const resultsProgram = (cells: Arr.NonEmptyReadonlyArray<Answer>, entry: Entry): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/api/results.ts: every answer a public reader gives is Effect's Result.",
		preludeFrom(prelude, entry),
		[
			{ owner: batchOwned, lines: resultsHeader },
			...Arr.map(cells, (answer, at) => ({
				owner: caseOwned(at),
				lines: [
					`// ${answer}`,
					`export type r${at} = Expect<Equals<Verdict<${answers[answer]}>, [true, false]>>`
				]
			}))
		]
	)
]
