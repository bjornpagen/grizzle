/**
 * XML's characters as XML Schema 1.0's regular expressions read them: the alphabet every pattern facet ranges over
 * (Char), the characters of a name (XML 1.0 Second Edition's Letter and NameChar), and the block table a block escape
 * names. One definition of each serves every reader: xs:NCName and its derivatives, a QTI identifier, a pair's or a
 * directedPair's value, and `\i` and `\c` in every pattern facet (spec readings 55 and 94, as DCM's clerk amended them,
 * 2026-11-19). XML 1.0 Fifth Edition's NameStartChar and NameChar are a markup name's, its parser's, never a pattern's.
 */

