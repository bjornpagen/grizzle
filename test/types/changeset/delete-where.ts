import { Array as Arr, Effect } from "effect"
import type { Refused } from "#compiler/core/refusals.ts"
import {
	callText,
	type DeleteWhereCase,
	deleteWhereCases,
	deleteWhereVerdict,
	overText,
	type Subject
} from "#test/support/agreement/delete-where.ts"
import { type PreludeAt, preludeAt, preludeFrom, preludeProgram } from "#test/support/prelude.ts"

/**
 * The deleteWhere program: every case of the deleteWhere box (test/support/agreement/delete-where.ts), its call written
 * with the typed builders, under the directive the type-test batch disarms exactly where the engine refuses the case
 * (deleteWhereVerdict), the oracle. The directive names the refusal the types give its subject or its shape, the first
 * its key breaks: a closed relation's key, a member keyed by its drawn index, a member of an immutable owner's family,
 * any other family's member, one that owns a sequence, a field outside the rows its delete names; any other refusal of
 * a value that is no parameter of its field's type, which the types refuse without a name.
 */

/** The refusal the types give a subject, before its selection: none for a relation a deleteWhere deletes. */
const subjectRefusal = (s: Subject): Refused | undefined => {
	switch (s) {
		case "Kind":
			return "a ChangeSet writes only the ordinary relations of its schema and the world relations its role writes"
		case "Line":
		case "Entry":
			return "a put or a delete names its rows by their key, and no fact states a key field grizzle writes: key the relation by fields its caller writes"
		case "Item":
			return "an immutable owner's family is fixed when its owner is inserted: declare the owner mutable to change it"
		case "Chip":
			return "deleteWhere deletes no family's member: grizzle edits a family from the rows a ChangeSet states, so delete a member from an array or a Stream"
		case "Book":
			return "a family's member that owns a sequence is written by inserting its owner with its rows nested"
		case "Task":
		case "Manual":
		case "Budget":
		case "Ticket":
		case "Ledger":
		case "Tag":
		case "Order":
		case "Cart":
		case "Pool":
		case "Bin":
		case "Node":
			return undefined
	}
}

/** The directive a case the engine refuses stands under. */
const directiveOf = (c: DeleteWhereCase): string => {
	const named = subjectRefusal(c.subject)
	if (named !== undefined) {
		return `// @ts-expect-error -- refusal: ${named}`
	}
	switch (c.shape) {
		case "a field outside its rows":
			return "// @ts-expect-error -- refusal: deleteWhere selects by the fields its delete's rows state: a tree's root fields, any other relation's written fields"
		case "none":
		case "parameters":
		case "literals":
		case "a parameter of another type":
		case "a typed constant":
		case "a Compute term":
		case "a variable":
			return `// @ts-expect-error -- refused: ${c.shape} is no parameter of its field's type nor a literal of it`
	}
}

/** A case's call, under its directive where the engine refuses it. */
const caseBlock = (c: DeleteWhereCase, index: number): string => {
	const refused = deleteWhereVerdict(c).kind === "refused"
	const call = `${refused ? `\t${directiveOf(c)}\n` : ""}\t${callText(c)}`
	return c.shape === "a variable"
		? `// ${c.subject}, ${c.shape}
export const where${index} = query(Work).rule((r) => {
	const t = v(Task, "t")
	void ChangeSet.empty(${overText(c)})
	${call}
	return r.match(Task, t).find(t)
})
`
		: `// ${c.subject}, ${c.shape}
export const where${index} = ChangeSet.empty(${overText(c)})
${call}
`
}

/** The program's prelude (test/support/programs/delete-where.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/delete-where.ts"))

/** The program's prelude as its directory reaches it, `entry` spelling a repository path from there. */
export const deleteWhereEntriesFrom = (entry: (path: string) => string): PreludeAt =>
	preludeFrom(prelude, entry)

/** The program over every case, its imports read through its prelude as `entries` reaches it. */
export const deleteWhereSource = (entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/changeset/delete-where.ts over ${deleteWhereCases.length} cases.`,
		entries,
		Arr.join(Arr.map(deleteWhereCases, caseBlock), "\n")
	)
