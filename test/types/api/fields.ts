import { Array as Arr, Effect } from "effect"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { batchOwned, caseOwned, type Entry, type Program } from "#test/support/types/batch/batch.ts"

/**
 * The term-is-no-field program: the box of every public reader that takes a field, each given a term where the field
 * stands, one line of a program the type batch checks. A term carries a column, an SQL type, a domain and a language as
 * a descriptor does, and is no field: the field registry marks every descriptor it makes (scalar/registry.ts
 * defineDescriptor, core/phantom.ts FieldMarked), FieldBase requires the mark, and no term has it, so each reader
 * refuses the term as its argument's type, where its builder refuses it at run time, a term being no descriptor the
 * registry owns.
 *
 * The oracle: a term is never a field. Each cell's line is refused at the term, by the code its reader's parameter
 * raises: a member of an object literal that is no field, TS2741 ([field] missing), and an argument that is none,
 * TS2345 where the parameter intersects its field with what it reads of it.
 */

/** Each reader of the box, by its line over the batch's term, and the code its refusal raises. */
const readers = {
	"a relation's field": ['relation("T", { id: term }, ["id"])', "TS2741"],
	"a generated relation's written field": [
		'relation.generated("T", { id: term }, ["id"], () => ({}))',
		"TS2741"
	],
	"accumulated's type": ["accumulated(term, 0n)", "TS2741"],
	"generated's type": [
		'relation.generated("T", { id: Id, n: int8 }, ["id"], (r) => ({ g: generated(term, r.n) }))',
		"TS2345"
	],
	"a contract's base": ['domain<typeof probeKey>()("C", term, (v) => Logic.gt(v, 0n))', "TS2345"],
	"codecText's field": ["codecText(term)", "TS2345"],
	"lexicalForm's type": ["lexicalForm(term)", "TS2741"],
	"lexical's type": ["lexical(term)", "TS2741"]
} as const

type Reader = keyof typeof readers

/** The cells of fieldsBox, minted as a dictionary in its door (test/types/api/fields.dictionary.ts). */
export const fieldsBoxItems: Arr.NonEmptyReadonlyArray<Reader> = [
	"a relation's field",
	"a generated relation's written field",
	"accumulated's type",
	"generated's type",
	"a contract's base",
	"codecText's field",
	"lexicalForm's type",
	"lexical's type"
]

/** The program's prelude (test/support/programs/fields.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/fields.ts"))

/** The term every cell passes where its reader takes a field: a bigint literal, of a type every reader admits. */
const fieldsHeader: ReadonlyArray<string> = [
	"export const term = Type.literal(int8, 1n)",
	'export const probeKey = Symbol("Probe")',
	""
]

/** The program over a batch's cells, its imports read through its prelude as `entry` reaches it. */
export const fieldsProgram = (cells: Arr.NonEmptyReadonlyArray<Reader>, entry: Entry): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/api/fields.ts: a term is never a field.",
		preludeFrom(prelude, entry),
		[
			{ owner: batchOwned, lines: fieldsHeader },
			...Arr.map(cells, (reader, at) => {
				const [line, code] = readers[reader]
				return {
					owner: caseOwned(at),
					lines: [
						`// ${reader}`,
						`// @ts-expect-error -- ${code}: a term is no field`,
						`export const r${at} = ${line}`
					]
				}
			})
		]
	)
]
