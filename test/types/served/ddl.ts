import { Array as Arr, Effect } from "effect"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { caseOwned, type Entry, type Program } from "#test/support/types/batch/batch.ts"

/**
 * No statement a served call or the rule judge sends is DDL (sql/ast.ts Dml, PlStatement): a served write's statement
 * holds a Dml AST at every door it passes from its builder to its served file (write/insert/statement.ts Built and
 * WriteStatement, write/program/artifact.ts PlacedStatement and ArtifactStatement), and a PL/pgSQL statement of a
 * capture, the judge and its parts and blocks has no DDL kind, its data-modifying statements a Dml's. So no served
 * statement can create, alter or drop an object, a temporary one included: a connection's life after install writes no
 * catalog row, where each session stood up its rule deltas as temporary tables, whose invalidations every backend of the
 * database read, and under connection churn reset and replanned every judge and trigger (METIS-PERFBAR).
 *
 * The box, exhausted and printed as one program the type batch checks disarmed: each statement family of SqlStatement
 * (Dml, Ddl, TransactionControl, FillStored) through each door that holds a served statement's AST, and the PL/pgSQL
 * statement's kinds against Ddl's. The oracle: a door takes Dml and refuses every other family, and no PL/pgSQL
 * statement's kind is a Ddl's. Each refusal stands under a `refused` directive: the contract is that the line does not
 * compile, whichever diagnostic the checker elaborates it to.
 */

/** A family of SqlStatement, and whether a served statement may be one. */
interface Family {
	readonly name: string
	readonly type: string
	readonly served: boolean
}

const families: Arr.NonEmptyReadonlyArray<Family> = [
	{ name: "a DML statement", type: "Dml", served: true },
	{ name: "a DDL statement", type: "Ddl", served: false },
	{ name: "a transaction's control", type: "TransactionControl", served: false },
	{ name: "a stored table's fill", type: "FillStored", served: false }
]

/** A door that holds a served statement's AST, by the type of its AST. */
interface Door {
	readonly name: string
	readonly ast: string
}

const doors: Arr.NonEmptyReadonlyArray<Door> = [
	{ name: "a builder's statement (Built)", ast: 'Built<never>["ast"]' },
	{ name: "a write statement (WriteStatement)", ast: 'WriteStatement["ast"]' },
	{ name: "a placed statement (PlacedStatement)", ast: 'PlacedStatement["ast"]' },
	{ name: "an artifact's statement (ArtifactStatement)", ast: 'ArtifactStatement["ast"]' },
	{
		name: "a PL/pgSQL statement's data-modifying statement",
		ast: 'Extract<PlStatement, { readonly kind: "modify" }>["statement"] | Dml'
	},
	{
		name: "a PL/pgSQL statement's INTO statement",
		ast: 'Extract<PlStatement, { readonly kind: "into" }>["statement"] | Dml'
	}
]

/** A cell of the box: a family through a door, or the PL/pgSQL statement's kinds against Ddl's. */
type ServedDdlCell =
	| Readonly<{ kind: "door"; family: Family; door: Door }>
	| Readonly<{ kind: "plKinds" }>

/** The cells of servedDdlBox, minted as a dictionary in its door (test/types/served/ddl.dictionary.ts). */
export const servedDdlBoxItems: Arr.NonEmptyReadonlyArray<ServedDdlCell> = [
	...Arr.flatMap(families, (family) =>
		Arr.map(doors, (door): ServedDdlCell => ({ kind: "door", family, door }))
	),
	{ kind: "plKinds" }
]

/** A cell's lines. */
const cellLines = (cell: ServedDdlCell, index: number): ReadonlyArray<string> => {
	switch (cell.kind) {
		case "door":
			return [
				`// ${cell.family.name}, through ${cell.door.name}`,
				`declare const statement${index}: ${cell.family.type}`,
				...(cell.family.served
					? []
					: [`// @ts-expect-error -- refused: ${cell.family.name} is no served statement`]),
				`export const held${index}: ${cell.door.ast} = statement${index}`
			]
		case "plKinds":
			return [
				"// the PL/pgSQL statement's kinds against Ddl's",
				`export const plKinds${index}: [Extract<PlStatement["kind"], Ddl["kind"]>] extends [never] ? true : false = true`
			]
	}
}

/** The program's prelude (test/support/programs/served-ddl.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/served-ddl.ts"))

/** The program over a batch's cells, its imports read through its prelude as `entry` reaches it. */
export const servedDdlProgram = (
	cells: Arr.NonEmptyReadonlyArray<ServedDdlCell>,
	entry: Entry
): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/served/ddl.ts: statement families through the doors of a served statement.",
		preludeFrom(prelude, entry),
		Arr.map(cells, (cell, at) => ({
			owner: caseOwned(at),
			lines: [...cellLines(cell, at), ""]
		}))
	)
]
