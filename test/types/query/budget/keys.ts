import { indices } from "@bjornpagen/grizzle-text/base/array"
import { assert, defined } from "@bjornpagen/testing/assert"
import { Array as Arr, Effect } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { assertClean, type Measuring, measuredEach } from "#test/types/batch/measured.ts"

/**
 * The keyed-rule programs (keys.test.ts): one-rule queries whose evidence reads the keys of what they match
 * (types/evidence/evidence.ts HeadKeys), as edullm's ledger writes its grading rules (packages/ledger/src/grade.ts): a
 * rule over a relation of a composite key, V, keyed by four fields and a fifth; and a rule matching a query bound to its
 * relation parameter beside V, the bound query's facts at four fields of V's key, written `queries` times, the program
 * checked at two sizes. A rule's keys are the head fields that hold every field of a key of each match, or of none, and
 * what they determine: each key's fields read once, the head's terms once.
 */
export type KeyedShape = "a composite key" | "a bound query beside a composite key"

/** The cells of keyedQueries, minted as a dictionary in its door (test/types/query/budget/keys.dictionary.ts). */
export const keyedShapesItems: readonly [KeyedShape, ...ReadonlyArray<KeyedShape>] = [
	"a composite key",
	"a bound query beside a composite key"
]

/** One query of a shape, named q<i>. */
const queryOf = (shape: KeyedShape, i: number): string => {
	switch (shape) {
		case "a composite key":
			return `export const q${i} = query(S).rule((r) => {
	const { a, b, c, d, x, y } = v(V, "v")
	return r.match(V, { a, b, c, d, x, y }).find({ a, b, c, d, x, y })
})\n`
		case "a bound query beside a composite key":
			return `export const q${i} = query(S).rule((r) => {
	const k = base.bind({ ps: r.relation("ps", { a: Id }) })
	const { a, b, c, d, w } = v(k, "k")
	const { x, y } = v(V, "v")
	return r.match(k, { a, b, c, d, w }).match(V, { a, b, c, d, x, y }).find({ a, b, c, d, w, x, y })
})\n`
	}
}

/** The program of `queries` queries of a shape, its imports read through the gates' prelude as `entries` reaches it. */
const keyedProgram = (shape: KeyedShape, queries: number, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/query/budget/keys.ts at ${jsonText({ shape, queries })}.`,
		entries,
		`export const K = relation("K", { a: Id, b: Id, c: pg.integer, d: pg.integer, w: pg.integer }, ["a", "b", "c", "d"])
export const V = relation("V", { a: Id, b: Id, c: pg.integer, d: pg.integer, x: pg.integer, y: pg.integer }, ["a", "b", "c", "d", "x"])
export const S = schema("S", [K, V], [contained(on(V, "a", "b", "c", "d"), on(K, "a", "b", "c", "d"))])
export const base = query(S).rule((r) => {
	const ps = r.relation("ps", { a: Id })
	const { a } = v(ps, "p")
	const { b, c, d, w } = v(K, "k")
	return r.match(ps, { a }).match(K, { a, b, c, d, w }).find({ a, b, c, d, w })
})
${Arr.join(
	Arr.map(indices(queries), (i) => queryOf(shape, i)),
	""
)}`
	)

/** The queries of the smaller program; the larger writes twice as many, so the step adds `step` queries. */
const step = 10

/**
 * What one query of each shape adds to a program's instantiations, at most: what it added once a rule's keys read each
 * key's fields' needs once per match (types/evidence/evidence.ts NeedsOfKeys) and the head's terms once
 * (HeadEntries), find reading the rule's facts by their parts (types/query/rule.ts RuleFind).
 *
 * @limitKind measured
 * @owner the query facade's type cost gates (test/types/query/budget/keys.ts)
 * @unit instantiations a query adds
 * @scope one query of the shape, checked by one checker against the engine's and the shell's declarations, as
 *   test/types/batch/measured.ts checks a program
 * @evidence ~/.cache/grizzle-release/PERF-TYPES-tools/hk (prof.sh, led.sh: the rule's instantiations by alias with an
 *   instrumented TypeScript 5.9, ts5/prof.cjs, over micro programs and W1's grading rule) and keys.test.ts run with
 *   each bound at 0, whose assertion states what a query of each shape adds (PERF-TYPES-tools/keys-*.log,
 *   ~/.cache/grizzle/METISREDS-logs/keys-rosterin.log)
 * @observed 2026-11-21, 22:00 to 02:00 UTC; 2026-11-24
 * @environment cassowary, Ubuntu 26.04 arm64, 64 cores, load 200 to 400 from other sessions; Node 26.13.1, TypeScript
 *   7.1.0-beta (tsgo); grizzle at hub main 80fec8100 and lane PERF-TYPES's key cut over it, then at hub main
 *   4a0bbf034 and lane METISREDS's facts cut over it
 * @workload a schema of two relations and a bound query; 10 and 20 queries of each shape, each program checked alone
 * @result per added query: a composite key 2,240 instantiations (2,287 before the facts cut, 3,153 before the key
 *   cut), a bound query beside a composite key 3,306 (3,411 and 5,064 before); every program clean. Of the forms tried
 *   (PERF-TYPES-tools/pins-*.log), the head's entries read once per head with a key's needs walked at once cost least
 *   at every pin: walked once per needed variable, 2,664 and 3,878; with the inputs' needs walked apart from the
 *   key's, 2,355 and 3,487. Of the facts cut's forms (METISREDS-logs/keys-rosterin.log), find's record narrowed by
 *   r.in over the facts read whole cost 2,293 and 3,417; read by their parts, with the narrowing, 2,240 and 3,306
 * @decision the bound is the cut's own cost, exactly: a change that makes a keyed rule cost more is refused here, and a
 *   change that lowers it lowers the bound
 * @revalidate a TypeScript 7 or tsgo upgrade; another machine; any change to the evidence's key rule
 *   (types/evidence/evidence.ts HeadKeys) or the query facade's types that moves a keyed rule's cost, which states its
 *   cost here
 */
const addedAtMost: { readonly [S in KeyedShape]: number } = {
	"a composite key": 2240,
	"a bound query beside a composite key": 3306
}

/** How a shape prints. */
export const keyedShapeName = (shape: KeyedShape): string => `queries over ${shape}`

/**
 * The cost of a shape's queries, measured: both programs typecheck with no diagnostic, and the queries the larger adds
 * cost no more, each, than the shape's bound.
 */
export const keyedCost = (at: Measuring, shape: KeyedShape) =>
	Effect.gen(function* () {
		const measured = yield* measuredEach(
			at,
			Arr.map([step, 2 * step], (queries) => ({
				size: queries,
				source: (entries: PreludeAt) => keyedProgram(shape, queries, entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, keyedShapeName(shape))
		}
		const count = (i: number): number =>
			defined(measured[i], `the program of ${shape} at ${i}`).instantiations
		const added = (count(1) - count(0)) / step
		assert.ok(
			added <= addedAtMost[shape],
			`a query over ${shape} adds ${added} instantiations, more than ${addedAtMost[shape]}`
		)
	})
