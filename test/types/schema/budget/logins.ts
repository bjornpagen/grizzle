import { Array as Arr } from "effect"
import { indices } from "#compiler/core/array.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { type EqualSteps, equalSteps } from "#test/types/batch/measured.ts"

/**
 * The login-scale program (test/types/schema/budget/logins.test.ts): a login over a schema written as qti-pie's pantry
 * writes its own, at `relations` relations. Its relations are declared in modules, a record of ten relations each, and
 * the schema lists them by spreading each module's values, `[P, ...Object.values(M0), ...]`, so its list is an array
 * of the union of its relations, not a tuple. Each relation holds an id, its parent's id and a number, and the schema
 * holds each one's parent contained in P's ids and a key on its parent and number. Over it a level of queries,
 * schema.extend(...), holds a derived relation for each of the first `queried` modules, each a query over the first
 * relation of its module, with a key on each. Over that level stand:
 *
 * - a full role, every relation of both levels whole (wholeEntriesOf) and every relation it may write written
 *   (writableNamesOf), as pantry's author role is;
 * - its reads, a query over the role for each of the first `queried` modules, each its module's first relation
 *   selected by a parameter;
 * - its write, one ChangeSet over the schema that deletes the last module's first relation by a parameter and inserts
 *   into it;
 * - a login over the role, its workloads the reads and the write, each a workload of the role;
 * - and a ChangeSet over the role that inserts into the first relation of each of the first `queried` modules.
 *
 * Only the schema grows with the size: the queries, the workloads and the ChangeSets are as many at every size, and
 * the role, the login and the ChangeSet over the role each read the schema's whole record, so a cost per lookup that
 * grows with the relations makes the program's cost grow faster than its size.
 */

/** A module holds ten relations, and the program repeats with each module. */
const modulePeriod = 10

/** The modules the queries, the workloads and the ChangeSets read, as many at every size. */
const queried = 4

/** The relation counts the scale test checks: the largest is past qti-pie's 370 by more than half again. */
export const loginSizes: EqualSteps = equalSteps(modulePeriod * 20)

/** The j-th relation of module m. */
const relationName = (m: number, j: number): string => `R${m}x${j}`

/** Module m: its ten relations, then their record, M<m>, by their own names. */
const moduleSource = (m: number): string => `${Arr.join(
	Arr.map(
		indices(modulePeriod),
		(j) =>
			`export const ${relationName(m, j)} = relation("${relationName(m, j)}", { id: uuid, parent: uuid, n: pg.integer }, ["id"])\n`
	),
	""
)}export const M${m} = { ${Arr.join(
	Arr.map(indices(modulePeriod), (j) => relationName(m, j)),
	", "
)} }
`

/** Module m's laws: each relation's parent contained in P's ids, and a key on its parent and number. */
const lawsOf = (m: number): ReadonlyArray<string> =>
	Arr.flatMap(indices(modulePeriod), (j) => [
		`contained(on(${relationName(m, j)}, "parent"), on(P, "id"))`,
		`key(on(${relationName(m, j)}, "parent", "n"))`
	])

/** Module m's derived relation, D<m>: its first relation's ids and parents, over the stored level. */
const derivedSource = (m: number): string =>
	`export const D${m} = derived("D${m}", query(Base).rule((r) => {
	const { id, parent } = v(${relationName(m, 0)}, "d")
	return r.match(${relationName(m, 0)}, { id, parent }).find({ id, parent })
}))
`

/** Module m's read over the role: its first relation's ids under one parent, the parameter. */
const readSource = (m: number): string => `\tread${m}: query(Author).rule((r) => {
		const { id, parent } = v(${relationName(m, 0)}, "x")
		return r.match(${relationName(m, 0)}, { id, parent }).where(r.eq(parent, r.param("parent", uuid))).find({ id })
	})`

/** The program at `relations` relations, a whole number of modules past `queried`, its imports read through `entries`. */
export const generateLoginSource = (relations: number, entries: PreludeAt): string => {
	const modules = indices(Math.floor(relations / modulePeriod))
	const read = indices(queried)
	const last = relationName(modules.length - 1, 0)
	return preludeProgram(
		`// Generated by test/types/schema/budget/logins.ts with ${relations} relations.`,
		entries,
		`export const P = relation("P", { id: uuid }, ["id"])
${Arr.join(Arr.map(modules, moduleSource), "")}
export const Base = schema("LoginScale", [P, ${Arr.join(
			Arr.map(modules, (m) => `...Object.values(M${m})`),
			", "
		)}], [
${Arr.join(
	Arr.map(Arr.flatMap(modules, lawsOf), (law) => `\t${law}`),
	",\n"
)}
])
${Arr.join(Arr.map(read, derivedSource), "")}
export const Top = schema.extend(Base, "LoginScaleQueries", [${Arr.join(
			Arr.map(read, (m) => `D${m}`),
			", "
		)}], [${Arr.join(
			Arr.map(read, (m) => `key(on(D${m}, "id"))`),
			", "
		)}])
export const Author = role(Top, "author", wholeEntriesOf(Top), { write: writableNamesOf(Top) })
export const reads = {
${Arr.join(Arr.map(read, readSource), ",\n")}
}
declare const someId: Uuid
export const write = ChangeSet.empty(Top)
	.delete(${last}, query(Top).rule((r) => {
		const stored = v(${last}, "stored")
		return r.match(${last}, stored).where(r.eq(stored.parent, r.param("parent", uuid))).find(stored)
	}))
	.insert(${last}, [{ id: someId, parent: someId, n: 1 }])
export const App = login(Top, "app", [Author], { workload: [workload(Author, reads), workload(Author, { write })] })
export const authored = ChangeSet.empty(Author)${Arr.join(
			Arr.map(
				read,
				(m) => `.insert(${relationName(m, 0)}, [{ id: someId, parent: someId, n: 1 }])`
			),
			""
		)}
`
	)
}
