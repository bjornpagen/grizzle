/**
 * The runtime file of one declared schema's snapshot, in its migrations directory: what an application imports for
 * DbLayer.make, the members a layer reads (ServedSnapshot) and the fingerprint of the whole snapshot.
 */
export const snapshotFileName = "snapshot.json"

/**
 * The migration file of one declared schema's snapshot, beside snapshot.json: every member of the snapshot that file does
 * not hold, which only `grizzle generate`, check, drift and migrate read.
 */
export const manifestFileName = "manifest.json"

/**
 * The texts of a snapshot's two files as `grizzle generate` writes them (build.ts writeSnapshot) and every reader reads
 * them, each as its chunks (grizzle-text TextChunks): snapshot.json and manifest.json, which hold each member of the
 * committed snapshot (DeploySnapshot) once between them, under the one fingerprint snapshot.json records of its content
 * and the one seal manifest.json carries over both.
 */
export interface SnapshotFiles {
	readonly snapshot: TextChunks
	readonly manifest: TextChunks
}

/** How a stored relation's field is written, as the snapshot records it: by its caller; generated by PostgreSQL from its row, with the digest of its generation expression's canonical text; drawn
 * by grizzle from the nested arrays (a family's index or count, a tree's start or end), with the digest of what draws
 * it; or accumulated by grizzle on the host, with the digest of its start value and of what fills it (a fold, or a
 * containment riding a family's axis). What fills a field is its role and every law that says what it holds
 * (laws/model/fillers.ts Filler), so a changed expression, start, family, fold or copy changes the record, and the
 * migration draws the field again; a declaration that only renames what fills it changes nothing (deploy/diff/declared.ts).
 */
export type SnapshotWriting =
	| "caller"
	| "instant"
	| "place"
	| { readonly generated: string }
	| { readonly keyGenerated: string }
	| { readonly drawn: string }
	| { readonly accumulated: string }

/** A field of a stored relation as the snapshot records it: its installed column, the digest of its canonical
 * ScalarType (which is its identity) with every roster named by its name alone, and how it is written. A roster's
 * handles are no part of a field's recorded type: they are the roster's codes, which the roster's own record holds, so
 * a roster's growth changes no field. */
export interface SnapshotField {
	readonly name: string
	readonly column: ColumnIdent
	readonly type: string
	readonly writing: SnapshotWriting
}

interface SnapshotRelationOf<K extends "relation" | "closed" | "derived"> {
	readonly kind: K
	/** The table, roster domain or stored table identifier. */
	readonly ident: RelationIdent
	readonly mutable: boolean
	/** The schema level that declares it, and a derived relation's level over what it reads. */
	readonly level: number
}

/** A stored relation's heading in declared order, its primary key, and the attribute numbers its table has used: one
 * per column it was created with and per column added since, its dropped ones included, which PostgreSQL never reuses
 * and counts against tableMaxColumns. */
interface SnapshotHeading {
	readonly fields: ReadonlyArray<SnapshotField>
	readonly primaryKey: ReadonlyArray<string>
	readonly attnums: number
}

/**
 * A relation of the snapshot's theory, by kind: a stored relation with its heading; a roster, by its domain, with its
 * codes; a derived relation, whose fields are its view's columns, which its stored table object records, with
 * its meaning (physical/derived/meaning.ts definitionMeanings), by which a draft creates its view again exactly when what it
 * means changes (deploy/diff/diff.ts viewDropsOf).
 *
 * A roster's codes are code c at position c, each the live handle it names or the hole a removed handle left, and their
 * length is the next code, so no separate counter can disagree with them. A closed relation of any other arity has no
 * record: nothing is installed under its name, and its rows reach the database only as the content-addressed constants
 * and the migration's checks the manifest and the laws record.
 */
export type SnapshotRelation =
	| (SnapshotRelationOf<"relation"> & SnapshotHeading)
	| (SnapshotRelationOf<"closed"> & { readonly codes: RosterCodes })
	| (SnapshotRelationOf<"derived"> & { readonly meaning: string })

/** A law of the snapshot's theory by how it is enforced: natively, by its shape alone; a law that reads closed
 * relations only, once by the migration that installs them, with the digest of the violation query that migration
 * runs, which a change of the law or of the rows it reads changes; or a rule over a query, by its triggers, with the
 * digest of the violation query the migration that adds or changes it runs. */
export type SnapshotLaw =
	| { readonly kind: "native"; readonly shape: string }
	| { readonly kind: "migration" | "trigger"; readonly shape: string; readonly digest: string }

export interface SnapshotTheory {
	/** The owned schema's fingerprint. */
	readonly schema: SchemaFingerprint
	readonly relations: Readonly<Record<string, SnapshotRelation>>
	readonly laws: Readonly<Record<string, SnapshotLaw>>
	/**
	 * The installation's spelling of each pattern language it installs, by the language's key (ir/pattern.ts
	 * Spellings): its history, which the next draft installs each of those languages by again, as a roster's codes are.
	 */
	readonly spellings: Readonly<Record<string, string>>
}

/**
 * A level of the installation as the snapshot records it, root first: its declared name, the PostgreSQL schema its
 * relations live in, its own fingerprint, the owned fingerprint of the schema it tops, by which a login over it is
 * served (DbLayer.make admits a login over any level the snapshot records), and each law it states that the levels
 * below it do not, by its law identity, as an outcome names it. A Db over a lower level holds none of a higher level's
 * code, so it reports a refusal by one of these as the law `above` names (types/changeset Law); the root states none
 * above anything, and records the laws of its own alike.
 */
export interface SnapshotLevel {
	readonly name: string
	readonly schema: string
	readonly fingerprint: SchemaFingerprint
	readonly laws: ReadonlyArray<DescribedLaw>
}

/** A login of an installation as the snapshot records it, under its declared name: its PostgreSQL role, whose name
 * the naming door derives from the installation's and the login's (core/identity.ts identity.login). A declared rename
 * of the login (deploy/diff/plan.ts Declarations) renames this role in place, so the record names one role across it. */
export interface SnapshotLogin {
	readonly role: string
}

/**
 * The members of a schema snapshot whose installation manifest is `M`: the compile's, every object whole with its
 * reasons, its state and its phase, in the snapshot's content (SnapshotContent); or the record a committed snapshot
 * holds (DeploySnapshot).
 *
 * A snapshot is the canonical serialization of what an installation is. It holds a summary of the CheckedTheory (its
 * relations, their fields and mutability, its rosters' codes, and its laws), the installation manifest with every
 * object's DDL and justification (a law identity, the workload's access, or the enforcement of a declaration), the
 * constraint-to-law map, each login by its declared name with its PostgreSQL role, each login's workload programs'
 * access (ProgramAccess: the paths each program reads through, by login and program name) and the access
 * requests they make. The next migration is drafted from the committed one, the current schema and the current
 * workloads, never from the live catalog, and DbLayer.make and `grizzle check` compare the workloads' access with it,
 * naming a program whose access moved. A program edit that moves no path leaves it unchanged. Its history is each
 * roster's codes and each table's attribute numbers: everything else in it is derived from the current schema and those
 * codes alone, so a fresh installation and a migrated one are the same snapshot exactly when no roster has a hole or a
 * renamed handle and no table a dropped column.
 */
interface SnapshotMembers<M> {
	/**
	 * The installation's root's declared name and PostgreSQL schema, which name the installation: its migrations
	 * directory, its ledger's schema and its empty snapshot's fingerprint, whatever levels stand above the root.
	 */
	readonly schemaName: string
	readonly schema: string
	/** The installed levels, root first; none before the first migration. */
	readonly levels: ReadonlyArray<SnapshotLevel>
	readonly theory: SnapshotTheory
	readonly manifest: M
	readonly constraintToLaw: ConstraintLaws
	/** Each login the installation creates, by its declared name. */
	readonly logins: Readonly<Record<string, SnapshotLogin>>
	readonly workload: WorkloadAccess
	readonly accessPaths: ReadonlyArray<StoredIndexRequest>
	/**
	 * The installation's live plan (live/notify.ts LivePlan): every stored relation a login's read program reads, each with
	 * every field some read program routes a change of it by, and every stored derived relation one reads
	 * (program/workload/compile.ts WorkloadPlan live). snapshot.json holds it, under the fingerprint: what the
	 * installation signals a change of is part of what it is.
	 */
	readonly live: LivePlan
}

/**
 * A snapshot's content, what its fingerprint digests: its members with the compile's installation manifest, every
 * installed statement whole. The fingerprint is SHA-256, in the domain `snapshot`, over its canonical text (build.ts
 * contentForm), so it covers the manifest, the workload access and the rosters' codes as well as the owned schema's
 * own fingerprint (`theory.schema`): a program whose access moves, or a roster whose handle is removed, is a new
 * snapshot. It is what a folder's meta.json and the migrations ledger record as the source and target of each migration
 * and what every Db's prologue guards. Only a compile holds it whole: the committed snapshot records it (DeploySnapshot).
 */
export type SnapshotContent = SnapshotMembers<InstallationManifest<SqlStatement>>

/**
 * The committed schema snapshot: a snapshot's content as its two files record it (SnapshotFiles), under the fingerprint
 * of the whole content. snapshot.json holds what an application reads; manifest.json holds the rest, its installation
 * manifest recorded (snapshot/recorded.ts RecordedManifest): every installed statement whole but a PL/pgSQL function's
 * and a constant's, each by its header, a function with its source's digest, and no object's reasons, state or phase,
 * which no reader of a committed snapshot reads. The record is what a draft reads of the installation it migrates from,
 * where only the record can say what is installed, since the schema has changed since, and what the drift check judges
 * a database by; manifest.json is sealed by its own digest over the whole record, its fingerprint included (build.ts
 * snapshotSeal), and `grizzle check` holds the record to the one the schemas compile to.
 */
export interface DeploySnapshot extends SnapshotMembers<RecordedManifest> {
	readonly fingerprint: SchemaFingerprint
}

/**
 * What an application's DbLayer and the Dbs it serves read of the committed snapshot, parsed once where the layer is
 * built from snapshot.json alone (served.ts servedSnapshot): the recorded fingerprint, which every Db's prologue guards
 * the database's ledger with; every level's PostgreSQL schema, the levels above the one the layer serves with the laws
 * each states, and the constraint-to-law map, which name a refusal by a law of a level above a Db's own
 * (witness/keylaw.ts lawsAbove); the installation's codes (codebookOf), its rosters' history, which no schema alone
 * determines; and the installation's derived runtime facts (SnapshotDerived). Nothing else of a snapshot reaches an application: `grizzle generate`, check, drift and migrate read the
 * whole DeploySnapshot, from both its files.
 */
export interface ServedSnapshot {
	readonly fingerprint: SchemaFingerprint
	/** Every level's PostgreSQL schema, root first. */
	readonly schemas: ReadonlyArray<string>
	/** Every level's recorded fingerprint, root first, which the layer owns its base's levels under, by position. */
	readonly fingerprints: ReadonlyArray<SchemaFingerprint>
	/** The levels above the one the layer serves, root first, each by its name with the laws it states. */
	readonly above: ReadonlyArray<Pick<SnapshotLevel, "name" | "laws">>
	readonly constraintToLaw: ConstraintLaws
	readonly codes: Codebook
	/** The installation's derived runtime facts, as snapshot.json records them beside its content. */
	readonly derived: SnapshotDerived
}

/**
 * The derived facts a level's artifacts compile under besides its codes (build.ts derivedFacts), which a login over a
 * lower level reads before the installation is compiled as well as after (adapter/served/login.ts artifactsUnder).
 */
export interface CompileFacts {
	/**
	 * Each closed relation's constants as readers address them, by the relation's declared name, rosters aside: every
	 * function by its identifier, its key's layout and its payload's radices under the installation's codes
	 * (physical/ddl/constants.ts NamedClosed). generate plans them from the relations' rows, packing each string of
	 * cells to name it by its digest; DbLayer.make reads them here and packs nothing.
	 */
	readonly closed: ClosedNames
	/**
	 * The foreign key graph's strongly connected components of more than one relation, names in code point order, which a
	 * login's compile reads for its deferral (laws/model/model.ts FkCycles). generate plans them from every law;
	 * DbLayer.make reads them here.
	 */
	readonly fkCycles: FkCycles
	/**
	 * The parts whose fixed targets take the shared reference (laws/model/plan.ts ReferenceChoice), which a login's
	 * compile reads for each reference it plans. generate chooses them over every law; DbLayer.make reads them here and
	 * chooses none.
	 */
	readonly references: ReferenceChoice
	/**
	 * The relations whose writes the installation's rule judge captures, in code point order (laws/model/model.ts
	 * LawModel `judged`), which a write's stand-ups stand up where it writes one (write/program/stand-up.ts
	 * writeStandUps). generate plans them from every law of every level; DbLayer.make reads them here, whose level holds
	 * no rule of a level above it, and plans none.
	 */
	readonly judged: ReadonlyArray<string>
	/**
	 * Each structural text domain the installation holds, by its pattern language's key, with the digest that names it
	 * (physical/ddl/domains.ts TextDomainNames), which every compile names a refined text's domain by. generate plans
	 * them from every artifact and served program (physical/install/plan.ts artifactObjects, ServedTypes); DbLayer.make
	 * reads them here and collects none.
	 */
	readonly textDomains: TextDomainNames
	/**
	 * The library functions the installation installs (ir/physical.ts LibraryFn), in name order, which every compile
	 * calls only those of. generate plans them from every artifact and served program, as it plans the text domains;
	 * DbLayer.make reads them here and collects none.
	 */
	readonly library: ReadonlyArray<LibraryFn>
}

/**
 * What a law column holds, as the law model planned it (laws/model/plan.ts LawColumnPlan), by the field whose values it
 * holds: a term's, its relation's own field where the law's selection holds; a constant's, the value a target fixes its
 * field to; a family's drawn index's or count's; or the predecessor of a drawn index of its family.
 */
export type LawColumnHolds =
	| { readonly kind: "term"; readonly field: string }
	| { readonly kind: "constant"; readonly target: string; readonly field: string }
	| { readonly kind: "drawn"; readonly field: string }
	| { readonly kind: "predecessor"; readonly field: string }

/**
 * A column an index key reads: a field of the relation, by its declared name, or a law column the law model adds to the
 * relation, by what it holds and the laws the manifest records it for.
 */
export type IndexedColumn =
	| { readonly kind: "field"; readonly field: string }
	| {
			readonly kind: "law"
			readonly holds: LawColumnHolds
			readonly laws: ReadonlyArray<LawId>
	  }

/**
 * One key column of an index, in the index's key order: a column it holds (IndexedColumn), or the suffix key of a text
 * field, which a law's probe seeks a suffix through (sql/suffix.ts); with its direction, a B-tree's ascending or
 * descending, or none for an index that orders nothing (GiST, HNSW, hash).
 */
export type IndexKeyColumn = { readonly direction: "asc" | "desc" | "none" } & (
	| IndexedColumn
	| { readonly kind: "suffix"; readonly of: IndexedColumn }
)

/**
 * An index the installation holds: its key columns in order (IndexKeyColumn), and the reasons its manifest records for it
 * (ir/products.ts PhysicalReason).
 */
export interface SnapshotIndex {
	readonly columns: NonEmptyReadonlyArray<IndexKeyColumn>
	readonly reasons: ReadonlyArray<PhysicalReason>
}

/**
 * An installed table as a plan names it: the declared name of the relation it stores, a stored
 * relation's or a stored derived relation's, and each index PostgreSQL holds on it, by the index's name
 * (SnapshotIndex). A primary key's, a unique key's and an exclusion constraint's index is named by its constraint,
 * which PostgreSQL names the index after, and a created index by its CREATE INDEX.
 */
export interface SnapshotTable {
	readonly relation: string
	readonly indexes: Readonly<Record<string, SnapshotIndex>>
}

/**
 * Tables of an installation as EXPLAIN (VERBOSE) names them, by their PostgreSQL schema, then by
 * their own name (SnapshotTable).
 */
export type SnapshotTables = Readonly<Record<string, Readonly<Record<string, SnapshotTable>>>>

/**
 * The facts snapshot.json records beside the snapshot's content for DbLayer.make, derived from the installation's
 * compile and no part of the content its fingerprint digests, so they change no fingerprint and no database's ledger:
 * `grizzle generate` writes them from the compile it drafts from (build.ts derivedOf), and the served compile reads them
 * instead of compiling them again: the facts a level's artifacts compile under (CompileFacts), and every table and
 * stored table the installation installs with its indexes (`tables`), which a login's served file cuts to its
 * own statements' (adapter/served/project.ts) and an explain names a plan's relations and indexes by, its live source
 * and its served parameters' types.
 */
export interface SnapshotDerived extends CompileFacts {
	readonly tables: SnapshotTables
	/**
	 * The installation's live source in installed terms (live/notify.ts LiveSource), which a login's served file holds
	 * with the texts its leader and listeners send (program/live.ts servedLiveOf).
	 */
	readonly live: LiveSource
	/**
	 * The types the installation casts its served programs' parameters to, in installed terms (physical/ddl/domains.ts
	 * InstalledParams): a served compile under the snapshot casts a parameter only to these, and refuses one whose
	 * domain the installation lacks where it is compiled (physical/install/plan.ts ParamSource `recorded`).
	 */
	readonly params: InstalledParams
	/**
	 * Each derived relation the installation keeps live, by its declared name, with why (`LiveDerived`): the record a
	 * consumer reads to see which of its derived relations store no table, every read of one reading its definition,
	 * and what keeps each from being stored (analysis/derived/storage.ts). No compile reads it.
	 */
	readonly liveDerived: Readonly<Record<string, LiveDerived>>
	/**
	 * Each rule over a query whose probes of the rows a write adds to a relation read none of them at some occurrence of
	 * it, by its law's identifier, with each such relation and its proofs (`ProvedRelation`): the record a reviewer
	 * reads to see why the rule judge holds no block of a law over a relation's added rows. No compile reads it.
	 */
	readonly proved: Readonly<Record<string, NonEmptyReadonlyArray<ProvedRelation>>>
	/**
	 * The installation's planned queries (physical/planned/graph.ts PlannedGraph): what each of its functions' bodies,
	 * each trigger's by its event, and each referential action plans, and what each reaches, which a served compile walks
	 * from a call's own statements to bound the pg_stat_statements entries one call makes (program/planned.ts). No served
	 * file reads it.
	 */
	readonly planned: PlannedGraph
	/**
	 * The installation's indexes as coverage reads them, with the table of every relation one is on
	 * (physical/indexes/engine.ts IndexSet): what a served compile from the snapshot alone resolves every read of its
	 * programs by (engine.ts resolverOf), as generate's compile resolves them, so a read lands on one index whichever
	 * compile binds it, and a read no index serves is the asker's internal compiler error, never an index guessed.
	 */
	readonly indexSet: IndexSet
}

/**
 * A relation a rule over a query reads that its probes of a write's added rows spare at some occurrence, as
 * snapshot.json records it (laws/model/model.ts CoveredRelation): the relation; each sibling's cover, the relation of
 * the stored match beside the occurrence, the field pairs of the containment of its rows into the relation it is read
 * through, and what it pins, every field the occurrence reads (`read`), or a key of a closed relation (`fresh`, every
 * row a write adds of it a row of a new key); or a target's negation of it a sibling arm regains (`clock`, the fields
 * the negation binds and the relation's clocks the sibling reads, each no earlier than a clock of its scope); and the
 * sides of the relation's writes a block of the
 * rule still reads, none where it holds no block of the relation.
 */
export interface ProvedRelation {
	readonly relation: string
	readonly covers: NonEmptyReadonlyArray<ProvedCover>
	readonly sides: ReadonlyArray<"added" | "removed">
}

/** A sibling's cover of an occurrence (ProvedRelation `covers`), as snapshot.json records it. */
export type ProvedCover =
	| {
			readonly kind: "read"
			readonly sibling: string
			readonly pairs: NonEmptyReadonlyArray<{ readonly from: string; readonly to: string }>
	  }
	| {
			readonly kind: "fresh"
			readonly sibling: string
			readonly pairs: NonEmptyReadonlyArray<{ readonly from: string; readonly to: string }>
			readonly key: NonEmptyReadonlyArray<string>
	  }
	| {
			readonly kind: "clock"
			readonly fields: NonEmptyReadonlyArray<string>
			readonly clocks: NonEmptyReadonlyArray<string>
	  }

/**
 * Why the installation keeps a derived relation live (analysis/derived/storage.ts LiveReason), as snapshot.json records
 * it: `notUnitLocal`, the condition of unit-locality its definition lacks, with where; `unboundedUpkeep`, the declared
 * unit its upkeep would re-derive whole, the fields of its unit's key, and why its delta form bounds no upkeep, the
 * condition it lacks and where (core/causes.ts UncheckedDelta); `recursion`, a recursion over a unit no
 * founding write writes whole, which no delta rule keeps, with that unit and its key's fields; `unrepresentable`,
 * why its table could not hold its rows, as the refusal of its table states it; or `copy`, the relation whose rows,
 * projected onto a key of it, are its own.
 */
export type LiveDerived =
	| {
			readonly kind: "notUnitLocal"
			readonly condition: UnitLocalityCondition
			readonly detail: string
	  }
	| {
			readonly kind: "unboundedUpkeep"
			readonly unit: string
			readonly fields: ReadonlyArray<string>
			readonly delta: { readonly reason: UncheckedDelta["reason"]; readonly detail: string }
	  }
	| {
			readonly kind: "recursion"
			readonly unit: string
			readonly fields: ReadonlyArray<string>
	  }
	| { readonly kind: "unrepresentable"; readonly detail: string }
	| { readonly kind: "copy"; readonly relation: string }
