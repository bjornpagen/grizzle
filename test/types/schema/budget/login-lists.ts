/**
 * The login-list program (login-lists.test.ts): a list of logins as an installation states them, as metis's packages/database
 * logins.ts does its 23 (49 roles, 50 workloads, 909 programs): a tuple `satisfies ReadonlyArray<AnyLogin>`, passed to
 * defineConfig and mapped with roleNameOf, checked at three lengths, the longest past metis's. Each login holds two
 * roles over a schema of two levels and two workloads, one over a role and one over the lower level, each of
 * programsEach programs, as metis's average two of each and eighteen programs a workload.
 */

/** The logins of the shortest list; the others hold two and three times as many, the longest's 24 past metis's 23. */
const step = 8

/** The programs of each workload: metis's 909 over 50 workloads are about eighteen each. */
const programsEach = 18

/** A workload's programs: the query `q` under as many names, each beginning `prefix`, so no two workloads share one. */
const programsNamed = (prefix: string): string =>
	Arr.join(
		Arr.map(indices(programsEach), (k) => `${prefix}${k}: q`),
		", "
	)

/** Login i: its two roles, its two workloads and the login over them. */
const loginOf = (
	i: number
): string => `export const Ra${i} = role(Top, "ra${i}", wholeEntriesOf(Top))
export const Rb${i} = role(Top, "rb${i}", wholeEntriesOf(Top))
export const wa${i} = workload(Ra${i}, { ${programsNamed("a")} })
export const wb${i} = workload(Low, { ${programsNamed("b")} })
export const L${i} = login(Top, "l${i}", [Ra${i}, Rb${i}], { workload: [wa${i}, wb${i}] })
`

/** The program of `logins` logins, its imports read through the gates' prelude as `entries` reaches it. */
const loginListSource = (logins: number, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/schema/budget/login-lists.ts at ${jsonText({ logins })}.`,
		entries,
		`export const T = relation("T", { id: int4, n: int4 }, ["id"])
export const U = relation("U", { id: int4, w: int4 }, ["id"])
export const Low = schema("Low", [T], [])
export const Top = schema.extend([Low], "Top", [U], [])
export const q = query(Low).rule((r) => {
	const { id, n } = v(T, "t")
	return r.match(T, { id, n }).find({ id, n })
})
${Arr.join(Arr.map(indices(logins), loginOf), "")}export const LOGINS = [${Arr.join(
			Arr.map(indices(logins), (i) => `L${i}`),
			", "
		)}] as const satisfies ReadonlyArray<AnyLogin>
declare const connection: MigrationConnectionConfig
export const config = defineConfig({ schemas: [Top], logins: LOGINS, migrations: "migrations", rolePrefixBytes: 0, connection: () => connection })
export const names = Arr.map(LOGINS, (login: AnyLogin) => roleNameOf(login, {}))
`
	)

/**
 * The cells of loginLists, the list's one dimension, its length, minted as a dictionary in its door
 * (test/types/schema/budget/login-lists.dictionary.ts).
 */
export const loginListsItems = ["logins"] as const

/** The lengths the list is checked at. */
const lengths = equalSteps(step)

/** What the list's program is, as its gate names it. */
export const loginListName = (dimension: (typeof loginListsItems)[number]): string =>
	`a list of ${dimension} of two roles and two workloads each, checked against AnyLogin, configured and named, at ${Arr.join(
		Arr.map(lengths.sizes, (n) => `${n}`),
		", "
	)}`

/**
 * What one login adds to the list's program at most: what it added once a login's roles carried its workloads and no
 * programs (types/schema/world.ts LoginRole), whose programs are read only where a served role or a client reads them.
 *
 * @limitKind measured
 * @owner the login-list cost gate (test/types/schema/budget/login-lists.ts)
 * @unit instantiations a login adds
 * @scope one login of two roles and two workloads of eighteen programs each in the list, checked by one checker against
 *   the engine's and the shell's declarations, as test/support/types/batch/measured.ts checks a program
 * @evidence login-lists.test.ts run with the bound at 0, whose assertion states what a login adds, at grizzle main
 *   a080f0837 with the cut and with the cut reverted (LoginRoles' roles carrying ProgramsOf<R, Ws>)
 * @observed 2026-11-23, 12:30 to 13:00 UTC
 * @environment cassowary, Ubuntu 26.04 arm64, load 200 to 270 from other sessions; Node 26.13.1, TypeScript 7.1.0-beta
 *   (tsgo)
 * @workload lists of 8, 16 and 24 logins, each program checked alone
 * @result per added login: 1,709 instantiations with the cut, 2,237 with each role's programs read in the login's type;
 *   at REPLAYFIX's exact-bound car (2026-11-26, over ousxtqsu on train C's 1170fa12 and its empty-level car), every type
 *   budget run with each program's count logged, width 8, load in the hundreds: 1,710 a login (84,981, 98,661 and
 *   112,341 instantiations at 8, 16 and 24 logins), one more than the 1,709 its parent b6236fb3 and train C's
 *   empty-level car measured; with a login's check that its roles are named apart from it (types/schema/world.ts
 *   RolesNamedApart over its roles' names, lane APIPOLISH, 2026-11-28), measured as this test measures it: 1,716 a
 *   login, 6 more, the conditional over its roles' names, read off them as one indexed access (11 more read by a
 *   conditional over each role, 17 more over each role with a literal test of each name).
 * @decision the bound is the count at the tree it was last measured at, exactly, the counts being a function of the
 *   tree: a change that makes a login cost more fails here and moves the bound in its own commit, its cost stated, and
 *   a change that lowers it lowers the bound. 1,710 is 1,709 and one: a login's workload over a role reads the role's
 *   queries at QueryOver of each of its levels, which admits a query over the empty level beside one over that level
 *   (types/query/query.ts), one instantiation each, the cheapest form of the empty level as the level below every root
 *   that keeps a query over it a query over every level: as a member of every level's levels (LevelsOf) a login cost
 *   1,736; as the least phantom every program carries, 1,709 a login but 30 more a flat served unit and 90 a nested one
 *   (served-records.ts), paid by every query instantiated; with the empty level in IsLevelOf's refusal branch beside
 *   it, 1,728
 * @revalidate a TypeScript 7 or tsgo upgrade; another machine; any change to a login's, a role's or a workload's type
 *   (types/schema/world.ts, types/db/workload.ts) that moves a login's cost, which states its cost here
 */
const addedAtMost = 1716

/**
 * The cost of the list, measured: its programs typecheck with no diagnostic, their instantiations grow no faster than
 * linearly, and each login the longer lists add costs no more than addedAtMost.
 */
export const loginListCost = (at: Measuring, dimension: (typeof loginListsItems)[number]) =>
	Effect.gen(function* () {
		const measured = yield* measuredEach(
			at,
			Arr.map(lengths.sizes, (size) => ({
				size,
				source: (entries: PreludeAt) => loginListSource(size, entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, loginListName(dimension))
		}
		const count = (size: number): number =>
			defined(
				Option.getOrUndefined(Arr.findFirst(measured, (m) => m.size === size)),
				`the list at ${size}`
			).instantiations
		incrementsDoNotGrow(count, lengths.half, `instantiations of ${loginListName(dimension)}`)
		const added = (count(2 * step) - count(step)) / step
		assert.ok(
			added <= addedAtMost,
			`a login adds ${added} instantiations, more than ${addedAtMost}`
		)
	})
