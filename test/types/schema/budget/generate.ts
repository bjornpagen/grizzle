import { Array as Arr } from "effect"
import { indices } from "#compiler/core/array.ts"
import { jsonText } from "#compiler/core/trusted.ts"
import type { BudgetEntries } from "#test/types/query/budget/generate.ts"

/**
 * The statement-scale program, one type test of schema(...), role(...) and the lookups by name at scale. It writes one
 * TypeScript program over the public barrels with `relations` relations: each holds a containment into the one before
 * it and every fourth a candidate key, all in one schema(...) call; a role over every relation; a role over a Pick of
 * half of them; and a query over the last relation. Every fourth relation, from the third, is relation.generated's, its
 * generated field's term typed by the row of its written fields alone: that callback's row and the relation's fields
 * are typed at every one of them, in the one schema(...) call.
 *
 * A schema's record holds each relation under its own name, so every lookup by name is one property read of the
 * record and the program's instantiations grow linearly with `relations`. A lookup through an index remapped with
 * `as` pays the index's size at every read, because the checker recomputes the keys of a remapped mapped type at each
 * `keyof`: under that index one schema(...) call stopped typechecking (TS2589) at 699 statements, and one role(...)
 * through Pick at a few hundred entries. The program asserts what is inferred at the first relation and at the last,
 * and keeps the refusals that must fire at scale; each carries a `@ts-expect-error -- TSnnnn` directive, which the
 * harness checks the way it checks the fixtures.
 *
 * The relation count the type-test batch checks.
 */
export const largestStatementSize = 2000

/** Whether relation i declares a generated field: every fourth, from the third, so neither the first nor the last. */
const generates = (i: number): boolean => i % 4 === 2

const relationDeclaration = (i: number): string =>
	generates(i)
		? `export const R${i} = relation.generated("R${i}", { id: uuid, parent: uuid, label: Label }, ["id"], (r) => ({ tag: generated(Label, r.label) }))\n`
		: `export const R${i} = relation("R${i}", { id: uuid, parent: uuid, label: Label }, ["id"])\n`

/** A candidate key on every fourth relation, and a containment chain from each relation into the one before it. */
const statements = (relations: number): string => {
	const lines: Array<string> = []
	for (let i = 0; i < relations; i++) {
		if (i % 4 === 0) {
			lines.push(`key(on(R${i}, "label"))`)
		}
		if (i > 0) {
			lines.push(`contained(on(R${i}, "parent"), on(R${i - 1}, "id"))`)
		}
	}
	return Arr.join(
		Arr.map(lines, (line) => `\t${line}`),
		",\n"
	)
}

const keysOf = (i: number): string =>
	i % 4 === 0 ? 'readonly ["id"] | readonly ["label"]' : 'readonly ["id"]'

/**
 * A complete program over `relations` relations that imports the schema, fields, text and query barrels from
 * `entries`.
 */
export const generateStatementSource = (relations: number, entries: BudgetEntries): string => {
	const last = relations - 1
	const names = Arr.join(
		Arr.map(indices(relations), (i) => `R${i}`),
		", "
	)
	const half = Arr.join(
		Arr.map(indices(Math.floor(relations / 2)), (i) => `"R${i}"`),
		" | "
	)
	return `// Generated by test/types/schema/budget/generate.ts with ${relations} relations.
import { contained, type Fact, key, type KeysOf, on, relation, role, schema } from ${jsonText(entries.schema)}
import { generated, type Uuid, uuid } from ${jsonText(entries.fields)}
import type { Addition } from ${jsonText(entries.changesetTypes)}
import { str } from ${jsonText(entries.text)}
import { type HeadOf, query, v } from ${jsonText(entries.query)}

type Equals<A, B> = (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false
type Expect<T extends true> = T

export const Label = str.regex("^[a-z]{1,32}$")
${Arr.join(Arr.map(indices(relations), relationDeclaration), "")}
export const S = schema("Scale", { ${names} }, [
${statements(relations)}
])

/** A role over every relation, and one over a Pick of half of them. */
export const Everything = role(S, "everything", S.relations)
declare const half: Pick<typeof S.relations, ${half}>
export const Half = role(S, "half", half)

export const lastIds = query(S).rule((r) => {
	const { id } = v(R${last}, "last")
	return r.match(R${last}, { id }).find({ id })
})
export type LastHead = Expect<Equals<HeadOf<typeof lastIds>, { readonly id: Uuid }>>
export type FirstKeys = Expect<Equals<KeysOf<typeof S, typeof R0>, ${keysOf(0)}>>
export type LastKeys = Expect<Equals<KeysOf<typeof S, typeof R${last}>, ${keysOf(last)}>>
/** A generated relation's fact holds its generated field; its addition holds the written fields alone. */
export type GeneratedFact = Expect<Equals<keyof Fact<typeof R2>, "id" | "parent" | "label" | "tag">>
export type GeneratedAddition = Expect<Equals<keyof Addition<typeof R2>, "id" | "parent" | "label">>

/** The refusals that must keep firing at scale. */
export const Stray = relation("Stray", { id: uuid, parent: uuid, label: Label }, ["id"])
// @ts-expect-error -- TS2345 refusal: a statement names a relation no level of the schema declares
export const undeclared = schema.extend(S, {}, [contained(on(Stray, "parent"), on(R${last}, "id"))])
// @ts-expect-error -- TS2322 refusal: a schema holds each relation under its own name
export const aliased = schema.extend(S, { Strays: Stray }, [])
// @ts-expect-error -- TS2322 refusal: a whole entry is a relation of the base under its own name
export const strayEntry = role(S, "stray", { R0, Stray })
`
}
