import { Array as Arr, Effect } from "effect"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { batchOwned, caseOwned, type Entry, type Program } from "#test/support/types/batch/batch.ts"

/**
 * The explicit-evidence program: each public type that takes an evidence, a query, an ordered query and a finished arm,
 * written by its caller with an evidence of each kind. An Evidence is admitted, its origins each an Origin; an evidence
 * whose card is no Card, whose origins hold a value that is no Origin, or whose values are no record is refused where it
 * is written (TS2344), as the type's own parameter holds it to Evidence whole. What a site that infers an evidence
 * requires of it, its keys and card alone (types/evidence/evidence.ts InferredEvidence), is no weaker bound on a type a
 * caller writes.
 */

/** A public type that takes an evidence: its name and how it is written over the program's schema and heading. */
interface EvidenceTaker {
	readonly name: "Query" | "Ordered" | "Finished"
	readonly written: (evidence: string) => string
}

/** An evidence a caller writes, and whether the type's parameter admits it. */
interface WrittenEvidence {
	readonly label: string
	readonly type: string
	readonly admitted: boolean
}

/** The cells of explicitEvidenceBox, minted as a dictionary in its door (test/types/evidence/explicit.dictionary.ts). */
export const explicitEvidenceBoxItems: Arr.NonEmptyReadonlyArray<EvidenceTaker> = [
	{ name: "Query", written: (evidence) => `Query<typeof S, Head, ${evidence}>` },
	{ name: "Ordered", written: (evidence) => `Ordered<typeof S, Head, ${evidence}>` },
	{ name: "Finished", written: (evidence) => `Finished<Head, ${evidence}>` }
]

/** The evidences every cell writes: one admitted, three refused. */
const evidences: Arr.NonEmptyReadonlyArray<WrittenEvidence> = [
	{
		label: "an Evidence, its origin an Origin",
		type: '{ readonly keys: readonly [ReadonlyArray<"id">]; readonly card: "many"; readonly origins: { readonly id: Origin<"P", "id", "p"> } }',
		admitted: true
	},
	{
		label: "a card that is no Card",
		type: '{ readonly keys: unknown; readonly card: "some" }',
		admitted: false
	},
	{
		label: "an origin that is no Origin",
		type: '{ readonly keys: unknown; readonly card: "many"; readonly origins: { readonly id: "P.id" } }',
		admitted: false
	},
	{
		label: "values that are no record",
		type: '{ readonly keys: unknown; readonly card: "many"; readonly values: 5 }',
		admitted: false
	}
]

/** The schema and heading every cell's types are over. */
const explicitHeader = (): ReadonlyArray<string> => [
	'export const P = relation("P", { id: pg.integer }, ["id"])',
	'export const S = schema("S", [P], [])',
	"export type Head = { readonly id: number }",
	""
]

/** A cell's lines: its type written with each evidence, the refused ones under their directive. */
const cellLines = (c: EvidenceTaker, at: number): ReadonlyArray<string> => [
	`// ${c.name}`,
	...Arr.flatMap(evidences, (e, i) => [
		...(e.admitted
			? []
			: [
					`// @ts-expect-error -- TS2344: ${c.name}'s evidence is held to Evidence whole: ${e.label}`
				]),
		`export type t${at}x${i} = ${c.written(e.type)}`
	]),
	""
]

/** The program's prelude (test/support/programs/explicit-evidence.ts). */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/explicit-evidence.ts"))

/** The program over a batch's cells, its imports read through its prelude as `entry` reaches it. */
export const explicitEvidenceProgram = (
	cells: Arr.NonEmptyReadonlyArray<EvidenceTaker>,
	entry: Entry
): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/evidence/explicit.ts: each public type that takes an evidence, written with one.",
		preludeFrom(prelude, entry),
		[
			{ owner: batchOwned, lines: explicitHeader() },
			...Arr.map(cells, (c, at) => ({ owner: caseOwned(at), lines: cellLines(c, at) }))
		]
	)
]
