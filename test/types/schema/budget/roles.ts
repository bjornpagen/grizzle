import { indices } from "@bjornpagen/grizzle-text/base/array"
import { assert, defined } from "@bjornpagen/testing/assert"
import { Array as Arr, Effect } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { assertClean, type Measuring, measuredEach } from "#test/support/types/batch/measured.ts"

/**
 * The role programs (roles.test.ts), each over a schema.extend of a base of `relations` relations, as edullm's pantry
 * and qti-database open their author, publisher and learner roles over a level whose derived relations their laws
 * read (pantry's Qti over QtiBase). The base holds relations R0 … of three fields, a natural id and two texts of one
 * type, Name, keyed by its package and id, under no law. Over it stand `derived` derived relations, D0 …, each the
 * facts of its own base relation, a view no role holds (a live one), and the extension lists them all, with a
 * candidate key over each one's `label`, the first statement naming it, and a key over the `id` of the first `laws`
 * of them. Each derived relation and each of its keys is passed to a generic call before the extension reads it, and a
 * query over the extension is read, as an application's programs over its level are: what using them costs anywhere.
 *
 * With `role`, a full role over the extension stands beside them, every relation whole (wholeEntriesOf) and every one it
 * may write written (writableNamesOf), as pantry's author role is, with what reads it: its keys of R0 (KeysOf, which
 * read the laws it keeps), a query over it, and a login whose workload over it holds the query over the extension and
 * a ChangeSet over the role. Without `role` the program is its control: the same base, extension and query alone.
 */
export type RoleShape = {
	readonly relations: number
	readonly derived: number
	readonly laws: number
	readonly role: boolean
}

/** The extension's laws: the keys over every derived relation's label, then the keys over the first `laws` ids. */
const lawsOf = (shape: RoleShape): string =>
	Arr.join(
		[
			...Arr.map(indices(shape.derived), (i) => `L${i}`),
			...Arr.map(indices(shape.laws), (i) => `K${i}`)
		],
		", "
	)

/** The full role over the extension and what reads it: its keys of R0, a query over it, and a login of it. */
const authorSource = `export const Author = role(E, "author", wholeEntriesOf(E), wholeWritesOf(E))
used(Author)
declare const authorKeys: KeysOf<typeof Author, typeof R0>
used(authorKeys)
export const own = query(Author).rule((q) => {
	const stored = v(Author.relations.R0, "stored")
	return q.match(Author.relations.R0, stored).find(stored)
})
used(own)
export const App = login(E, "app", [Author], {
	workload: [
		workload(Author, {
			read,
			write: ChangeSet.empty(Author).insert(Author.relations.R0, [{ id, label, package: label }])
		})
	]
})
`

/** A complete program at `shape`, its imports read through the gates' prelude as `entries` reaches it. */
const roleProgram = (shape: RoleShape, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/schema/budget/roles.ts at ${jsonText(shape)}.`,
		entries,
		`declare const used: <const X>(x: X) => void
export const Name = str.bytes(64, str.regex("^[a-z]+$"))
declare const label: Infer<typeof Name>
declare const id: Infer<typeof natural>
${Arr.join(
	Arr.map(
		indices(shape.relations),
		(i) =>
			`export const R${i} = relation("R${i}", { id: natural, label: Name, package: Name }, ["package", "id"])\n`
	),
	""
)}export const B = schema("B", [${Arr.join(
			Arr.map(indices(shape.relations), (i) => `R${i}`),
			", "
		)}], [])
${Arr.join(
	Arr.map(
		indices(shape.derived),
		(i) => `export const D${i} = derived("D${i}", query(B).rule((q) => {
	const stored = v(R${i}, "stored")
	return q.match(R${i}, stored).find(stored)
}))
used(D${i})
export const L${i} = key(on(D${i}, "label"))
used(L${i})
export const K${i} = key(on(D${i}, "id"))
used(K${i})
`
	),
	""
)}export const E = schema.extend([B], "E", [${Arr.join(
			Arr.map(indices(shape.derived), (i) => `D${i}`),
			", "
		)}], [${lawsOf(shape)}])
export const read = query(E).rule((q) => {
	const stored = v(R0, "stored")
	return q.match(R0, stored).find(stored)
})
used(read)
${shape.role ? authorSource : ""}`
	)

/**
 * The derived relations or laws of the first program, and the bases' sizes. The second program has twice as many; the
 * small base holds twice as many relations as the most derived relations, each of them over one of its own, and the
 * large one four times as many as the small, so a derived relation or a law that walks the base walks every relation
 * the large base adds, three for each of the small one's, for each relation or law the second program adds.
 */
const added = 5
const derivedCount = 2 * added
const small = 2 * derivedCount
const large = 4 * small

/** What one law measures: the shape of its first program over the base of `relations`, and of its second. */
export type RoleDimension = Readonly<{
	what: string
	shape: (relations: number, count: number, role: boolean) => RoleShape
}>

/** The cells of roleDimensions, minted as a dictionary in its door (test/types/schema/budget/roles.dictionary.ts). */
export const roleDimensionsItems: readonly [RoleDimension, ...ReadonlyArray<RoleDimension>] = [
	{
		what: "derived relation of the role's level, with a key over it",
		shape: (relations, count, role) => ({ relations, derived: count, laws: 0, role })
	},
	{
		what: "law over a derived relation of the role's level",
		shape: (relations, count, role) => ({ relations, derived: derivedCount, laws: count, role })
	}
]

/** The eight programs of one dimension, in order: `added` and twice as many, over each base, with the role and without. */
const roleShapes = Arr.flatMap([true, false], (role) =>
	Arr.map(
		[
			{ relations: small, count: added },
			{ relations: small, count: 2 * added },
			{ relations: large, count: added },
			{ relations: large, count: 2 * added }
		] as const,
		(at) => ({ ...at, role })
	)
)

/** How a dimension prints. */
export const roleDimensionName = (dimension: RoleDimension): string =>
	`a full role's cost for each ${dimension.what} over ${large} base relations and over ${small}`

/**
 * The cost of one dimension, measured: its eight programs typecheck with no diagnostic, and the role and its readers
 * add exactly as many instantiations for the last `added` of each over the large base as over the small one: (R − C)
 * at twice as many less (R − C) at as many, R the program with the role and C its control.
 */
export const roleCost = (at: Measuring, dimension: RoleDimension) =>
	Effect.gen(function* () {
		const measured = yield* measuredEach(
			at,
			Arr.map(roleShapes, (shape) => ({
				size: shape.relations,
				source: (entries: PreludeAt) =>
					roleProgram(dimension.shape(shape.relations, shape.count, shape.role), entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, `the role program of each ${dimension.what}`)
		}
		const count = (i: number): number =>
			defined(measured[i], `the program of each ${dimension.what} at ${i}`).instantiations
		const role = (i: number): number => count(i) - count(i + 4)
		const step = { small: role(1) - role(0), large: role(3) - role(2) }
		assert.equal(
			step.large,
			step.small,
			`the role adds ${step.large} instantiations for the last ${added} of each ${dimension.what} over ${large} base relations and ${step.small} over ${small}`
		)
	})
