import { Array as Arr, Order } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { query, v } from "#compiler/public/query.ts"
import { Account, Work } from "#test/support/agreement/access-schema.ts"

/**
 * The query facade's surface: the methods the public types promise on a query builder, a rule, a finished arm, a query
 * and an ordered query, against the methods the builders' values carry at run time. The oracle is the runtime: each
 * kind is built over Work (test/support/agreement/access-schema.ts), and its methods are read off the value, every
 * function-valued member by its string key, own or inherited below Object.prototype. The one program the type tier
 * checks (test/types/api/surface.test.ts) states, for each kind, that the function-valued keys of its public type equal
 * exactly those names, so a method the types promise and the value lacks, which a typed caller would call into a
 * TypeError, fails it, and so does a method the value carries and the types hide. A value's data, its decoders,
 * heading and Description, and the type-only phantom keys are no methods, and are compared on neither side.
 */
const kinds = ["QueryBuilder", "Rule", "Finished", "Query", "Ordered"] as const
type Kind = (typeof kinds)[number]

/** Each kind's public type, as the program names it over Work and a heading of one field. */
const typeOf: { readonly [K in Kind]: string } = {
	QueryBuilder: "QueryBuilder<S>",
	Rule: "Rule<S>",
	Finished: "Finished<Head, Evidence.Unknown>",
	Query: "Query<S, Head>",
	Ordered: "Ordered<S, Head>"
}

/** A value's function-valued members by string key, own or inherited below Object.prototype, in code point order. */
const methodsOf = (value: object): ReadonlyArray<string> => {
	const names = new Set<string>()
	for (
		let level: object | null = value;
		level !== null && level !== Object.prototype && level !== Function.prototype;
		level = Reflect.getPrototypeOf(level)
	) {
		for (const key of Reflect.ownKeys(level)) {
			const member: unknown = Reflect.getOwnPropertyDescriptor(level, key)?.value
			if (typeof key === "string" && typeof member === "function") {
				names.add(key)
			}
		}
	}
	return Arr.sort([...names], Order.String)
}

/** Each kind's runtime methods, read off a value of it the builders made over Work. */
const surfaces = (): { readonly [K in Kind]: ReadonlyArray<string> } => {
	const builder = query(Work)
	let rule: ReadonlyArray<string> = []
	let finished: ReadonlyArray<string> = []
	const built = builder.rule((r) => {
		rule = methodsOf(r)
		const { id } = v(Account, "account")
		const arm = r.match(Account, { id }).find({ id })
		finished = methodsOf(arm)
		return arm
	})
	return {
		QueryBuilder: methodsOf(builder),
		Rule: rule,
		Finished: finished,
		Query: methodsOf(built),
		Ordered: methodsOf(built.orderBy(["id", "asc"]))
	}
}

/** The modules the program imports, each spelled as an import specifier relative to the program's directory. */
interface SurfaceEntries {
	readonly query: string
	readonly schema: string
}

export const surfaceEntriesFrom = (entry: (path: string) => string): SurfaceEntries => ({
	query: entry("packages/engine/src/public/query.ts"),
	schema: entry("test/support/agreement/access-schema.ts")
})

/** The program: for each kind, its public type's function-valued keys equal the methods its runtime value carries. */
export const surfaceModule = (entries: SurfaceEntries): string => {
	const read = surfaces()
	return Arr.join(
		[
			"// Generated by test/types/api/surface.ts: the query facade's surface against the builders' values.",
			`import type { Evidence, Finished, Ordered, Query, QueryBuilder, Rule } from ${jsonText(entries.query)}`,
			`import type { Work } from ${jsonText(entries.schema)}`,
			"",
			"type Equals<A, B> = (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false",
			"type Expect<T extends true> = T",
			"/** A type's keys whose members are functions: its methods. */",
			"type Methods<T> = { readonly [K in keyof T]-?: T[K] extends (...args: never) => unknown ? K : never }[keyof T]",
			"type S = typeof Work",
			"type Head = { readonly id: string }",
			"",
			...Arr.map(kinds, (kind) => {
				const names = read[kind]
				return `export type m_${kind} = Expect<Equals<Methods<${typeOf[kind]}>, ${
					Arr.isReadonlyArrayNonEmpty(names) ? Arr.join(Arr.map(names, jsonText), " | ") : "never"
				}>>`
			}),
			""
		],
		"\n"
	)
}
