import { Array as Arr } from "effect"
import { indices } from "#compiler/core/array.ts"
import { jsonText } from "#compiler/core/trusted.ts"
import type { BudgetEntries } from "#test/types/query/budget/generate.ts"

/**
 * The schema-scale programs, one per schema dimension, each checked at n, 2n and 4n (scaling.test.ts). A program at a
 * shape writes `relations` relations R0 … over P, each with its id, its parent and `fields` uuid fields f0 …, and
 * `laws` laws: the first contains its parent in P's ids, as issue #9's schema does; then, field by field, a key on the
 * field and a containment of the field in P's ids, in turn. Over that schema it writes `roles` full roles, each read as
 * issue #9 reads one, `ChangeSet.empty(role)` and `query(role)`, each role with a query entry of its own, and over
 * the base, for each of the last `readers` relations, a ChangeSet and a query that read it by name: its addition,
 * holding every written field, and a rule matching every field.
 */
type SchemaShape = {
	readonly relations: number
	readonly laws: number
	readonly fields: number
	readonly roles: number
	readonly readers: number
}

/** One dimension: its name, the shape at n, and the shape at a size of its own along the dimension. */
interface SchemaDimension {
	readonly name: string
	readonly sizes: readonly [number, number, number]
	readonly shape: (size: number) => SchemaShape
}

/**
 * The dimensions and their sizes. The full role's entries reach past issue #9's cliff, 1,107 relations each with a law
 * under one full role, at which ChangeSet.empty(role) and query(role) failed with TS2589.
 */
export const schemaDimensions: ReadonlyArray<SchemaDimension> = [
	{
		name: "relations",
		sizes: [250, 500, 1000],
		shape: (relations) => ({ relations, laws: 1, fields: 1, roles: 0, readers: 1 })
	},
	{
		name: "full-role entries",
		sizes: [300, 600, 1200],
		shape: (relations) => ({ relations, laws: 1, fields: 1, roles: 1, readers: 1 })
	},
	{
		name: "laws per relation",
		sizes: [4, 8, 16],
		shape: (laws) => ({ relations: 100, laws, fields: 16, roles: 1, readers: 1 })
	},
	{
		name: "roles per schema",
		sizes: [4, 8, 16],
		shape: (roles) => ({ relations: 100, laws: 1, fields: 1, roles, readers: 1 })
	},
	{
		name: "fields per relation",
		sizes: [8, 16, 32],
		shape: (fields) => ({ relations: 25, laws: 1, fields, roles: 1, readers: 25 })
	}
]

const fieldNames = (fields: number): ReadonlyArray<string> =>
	Arr.map(indices(fields), (j) => `f${j}`)

/** Relation i's laws: its parent in P's ids, then a key and a containment on its fields, in turn. */
const lawsOf = (i: number, laws: number): ReadonlyArray<string> =>
	Arr.map(indices(laws), (j) =>
		j === 0
			? `contained(on(R${i}, "parent"), on(P, "id"))`
			: j % 2 === 1
				? `key(on(R${i}, "f${j - 1}"))`
				: `contained(on(R${i}, "f${j - 1}"), on(P, "id"))`
	)

/** What the program imports from the schema barrel: a key only where a relation has one, a role only where it writes one. */
const schemaImports = (shape: SchemaShape): ReadonlyArray<string> => [
	"contained",
	...(shape.laws > 1 ? ["key"] : []),
	"on",
	"relation",
	...(shape.roles > 0 ? ["role"] : []),
	"schema"
]

/**
 * Role g's own query entry, the ids of one relation: every role holds every relation of the base whole, a full role,
 * and one entry of its own, so no two roles are one type.
 */
const seenEntry = (g: number, relations: number): string =>
	`query(S).rule((r) => {
	const { id } = v(R${g % relations}, "seen")
	return r.match(R${g % relations}, { id }).find({ id })
})`

/** A complete program at `shape`, importing the schema, fields, ChangeSet and query barrels from `entries`. */
export const schemaScaleSource = (shape: SchemaShape, entries: BudgetEntries): string => {
	const last = shape.relations - 1
	const fields = fieldNames(shape.fields)
	const heading = Arr.join(
		Arr.map(["id", "parent", ...fields], (f) => `${f}: uuid`),
		", "
	)
	const written = Arr.join(
		Arr.map(["id", "parent", ...fields], (f) => `${f}: someId`),
		", "
	)
	const bound = Arr.join(["id", "parent", ...fields], ", ")
	return `// Generated by test/types/schema/budget/scaling.ts at ${jsonText(shape)}.
import { ChangeSet } from ${jsonText(entries.changeset)}
import { type Uuid, uuid } from ${jsonText(entries.fields)}
import { query, v } from ${jsonText(entries.query)}
import { ${Arr.join(schemaImports(shape), ", ")} } from ${jsonText(entries.schema)}

export const P = relation("P", { id: uuid }, ["id"])
${Arr.join(
	Arr.map(
		indices(shape.relations),
		(i) => `export const R${i} = relation("R${i}", { ${heading} }, ["id"])\n`
	),
	""
)}
export const S = schema("Scale", { P, ${Arr.join(
		Arr.map(indices(shape.relations), (i) => `R${i}`),
		", "
	)} }, [
${Arr.join(
	Arr.flatMap(indices(shape.relations), (i) => Arr.map(lawsOf(i, shape.laws), (law) => `\t${law}`)),
	",\n"
)}
])
${Arr.join(
	Arr.map(
		indices(shape.roles),
		(
			g
		) => `export const Full${g} = role(S, "full${g}", { ...S.relations, Seen${g}: ${seenEntry(g, shape.relations)} })
export const empty${g} = ChangeSet.empty(Full${g})
export const over${g} = query(Full${g})
`
	),
	""
)}
declare const someId: Uuid
${Arr.join(
	Arr.map(
		indices(shape.readers),
		(k) => `export const insert${k} = ChangeSet.empty(S).insert(R${last - k}, [{ ${written} }])
export const read${k} = query(S).rule((r) => {
	const { ${bound} } = v(R${last - k}, "read")
	return r.match(R${last - k}, { ${bound} }).find({ ${bound} })
})
`
	),
	""
)}`
}
