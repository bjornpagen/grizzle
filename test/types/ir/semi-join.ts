import { Array as Arr } from "effect"
import { relKinds } from "#compiler/ir/rel.ts"

/**
 * A semi-join's right side (packages/engine/src/ir/rel.ts SemiJoinRight): a node's constructor takes as a semi-join's
 * right side only a node semiJoinRight minted, which reads the node's subtree for a column of the left, so a node that
 * may read its left never stands there unread. The box is the IR's roster of node kinds (rel.ts relKinds), each a
 * built node a semi-join's right side may be, and the editor's cell: a semi-join over the minted node compiles, one over
 * the node as it is does not, and an anti-join over the node as it is compiles, since a negation's right side reads
 * the rule's variables. Each refusal stands under a `refused` directive: the contract is that the line does not
 * compile, whichever diagnostic the checker elaborates it to.
 */

/** Why the node as it is is refused as a semi-join's right side. */
const unminted =
	"a semi-join's right side is a SemiJoinRight that semiJoinRight minted, and a node as it is is none"

/** A built node of one kind of the roster as each join's right side. */
const builtBlock = (kind: string): string =>
	Arr.join(
		[
			`declare const right${kind}: NodeOf<"${kind}">`,
			`export const minted${kind} = semiJoinRight(builtSides, left, right${kind})`,
			`export const semi${kind} = minted${kind} === undefined ? undefined : b.node({ kind: "SemiJoin", left, right: minted${kind}, ...sides })`,
			`// @ts-expect-error -- refused: ${unminted}`,
			`export const unmintedSemi${kind} = b.node({ kind: "SemiJoin", left, right: right${kind}, ...sides })`,
			`export const anti${kind} = b.node({ kind: "AntiJoin", left, right: right${kind}, ...sides })`,
			""
		],
		"\n"
	)

/** The editor's cell as each join's right side. */
const cellBlock = Arr.join(
	[
		"declare const rightCell: Cell",
		"export const mintedCell = semiJoinRight(cellGraph, leftCell, rightCell)",
		'export const semiCell = mintedCell === undefined ? undefined : ed.add({ kind: "SemiJoin", left: leftCell, right: mintedCell, ...sides })',
		`// @ts-expect-error -- refused: ${unminted}`,
		'export const unmintedSemiCell = ed.add({ kind: "SemiJoin", left: leftCell, right: rightCell, ...sides })',
		'export const antiCell = ed.add({ kind: "AntiJoin", left: leftCell, right: rightCell, ...sides })',
		""
	],
	"\n"
)

/** The program over the box. */
export const semiJoinModule = (): string =>
	Arr.join(
		[
			"// Generated by test/types/ir/semi-join.ts: a semi-join's right side, minted and as it is, over every node kind and the editor's cell.",
			'import type { DagBuilder } from "../../../../packages/engine/src/ir/builder.ts"',
			'import { builtSides, type Cell, conservativeMeta, type NodeOf, type RelNode, semiJoinRight } from "../../../../packages/engine/src/ir/rel.ts"',
			'import { cellGraph, type DagEditor } from "../../../../packages/engine/src/lower/optimize/demand/editor.ts"',
			"",
			"declare const b: DagBuilder",
			"declare const ed: DagEditor",
			"declare const left: RelNode",
			"declare const leftCell: Cell",
			"const sides = { on: [], heading: [], loc: undefined, meta: conservativeMeta }",
			"",
			...Arr.map(relKinds, builtBlock),
			cellBlock
		],
		"\n"
	)
