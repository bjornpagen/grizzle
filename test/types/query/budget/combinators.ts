import { indices } from "@bjornpagen/grizzle-text/base/array"
import { assert, defined } from "@bjornpagen/testing/assert"
import { Array as Arr, Effect } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { assertClean, type Measuring, measuredEach } from "#test/support/types/batch/measured.ts"

/**
 * The combinator programs, one per combinator a query is written with beyond its first rule (combinators.test.ts), each
 * written over a schema of `relations` relations R0 … of three fields, an id, a package and a kind, keyed by the id,
 * with `queries` queries each built by the combinator over one of the first `sources` relations in turn: a union's
 * further arm, a rule matching a query bound to its relation parameter, an order and its take, a name, an attachment
 * of a query, and an attachment of an arm before it joins a query. Every program declares the same base queries, one
 * per source, so a query the second program adds costs its combinator alone, never what a base's first use reads once.
 * As edullm's ledger writes its grading statement (packages/ledger/src/grade.ts), union arm after union arm, each arm
 * matching a query bound to the call's relation parameter, over a level of hundreds of relations.
 */
type CombinatorShape = {
	readonly relations: number
	readonly queries: number
	readonly combinator: Combinator
}

/** A combinator a query is written with beyond its first rule, each a case of the gate. */
export type Combinator = "union" | "bind" | "order" | "name" | "attach" | "arm attach"

/** The cells of combinatorKinds, minted as a dictionary in its door (test/types/query/budget/combinators.dictionary.ts). */
export const combinatorsItems: readonly [Combinator, ...ReadonlyArray<Combinator>] = [
	"union",
	"bind",
	"order",
	"name",
	"attach",
	"arm attach"
]

/** The relations every program declares a base query over, its queries each built over one in turn. */
const sources = 5

/** One rule over relation j, in the scope `scope`: every field of it but the package, in its head. */
const armOver = (j: number, scope: string): string => `(r) => {
	const { id, kind } = v(R${j}, "${scope}")
	return r.match(R${j}, { id, kind }).find({ id, kind })
}`

/** A child of a parent `p`: the facts of relation j of the parent's id, over S. */
const childOver = (j: number): string => `(p) =>
		query(S).rule((r) => {
			const { kind } = v(R${j}, "c")
			return r.match(R${j}, { id: p.id, kind }).find({ kind })
		})`

/**
 * The base queries every program declares, one per source: q<j>, one rule over relation j; and, for a bind, b<j>, the
 * facts of relation j at the ids of its relation parameter `ps`.
 */
const baseQueries = (combinator: Combinator): string =>
	Arr.join(
		Arr.map(
			indices(sources),
			(j) =>
				`export const q${j} = query(S).rule(${armOver(j, "x")})\n${
					combinator === "bind"
						? `export const b${j} = query(S).rule((r) => {
	const ps = r.relation("ps", { id: Id })
	const { id } = v(ps, "p")
	const { kind } = v(R${j}, "x")
	return r.match(ps, { id }).match(R${j}, { id, kind }).find({ id, kind })
})\n`
						: ""
				}`
		),
		""
	)

/** Query i, built by the combinator over source i mod sources. */
const queryOf = (combinator: Combinator, i: number): string => {
	const j = i % sources
	switch (combinator) {
		case "union":
			return `export const u${i} = query(S).rule(${armOver(j, "a")}).rule(${armOver(j, "b")})\n`
		case "bind":
			return `export const u${i} = query(S).rule((r) => {
	const bound = b${j}.bind({ ps: r.relation("ps", { id: Id }) })
	const { id, kind } = v(bound, "b")
	return r.match(bound, { id, kind }).find({ id, kind })
})\n`
		case "order":
			return `export const u${i} = q${j}.orderBy(["id", "asc"]).take(1)\n`
		case "name":
			return `export const u${i} = q${j}.named("u${i}")\n`
		case "attach":
			return `export const u${i} = q${j}.attach("children", ${childOver(j)}, "array")\n`
		case "arm attach":
			return `export const u${i} = query(S).rule((r) => {
	const { id, kind } = v(R${j}, "a")
	return r.match(R${j}, { id, kind }).find({ id, kind }).attach("children", ${childOver(j)}, "array")
})\n`
	}
}

/** A complete program at `shape`, its imports read through the gates' prelude as `entries` reaches it. */
const combinatorProgram = (shape: CombinatorShape, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/query/budget/combinators.ts at ${jsonText(shape)}.`,
		entries,
		`export const Kind = str.regex("^[a-z]{1,8}$")
${Arr.join(
	Arr.map(
		indices(shape.relations),
		(i) => `export const R${i} = relation("R${i}", { id: Id, package: Id, kind: Kind }, ["id"])\n`
	),
	""
)}export const S = schema("S", [${Arr.join(
			Arr.map(indices(shape.relations), (i) => `R${i}`),
			", "
		)}], [])
${baseQueries(shape.combinator)}${Arr.join(
			Arr.map(indices(shape.queries), (i) => queryOf(shape.combinator, i)),
			""
		)}`
	)

/**
 * The queries of the first program, and the schemas' sizes. The second program writes twice as many queries, so the
 * small schema holds as many relations as the first program has queries; the large one holds four times as many, so a
 * combinator that walks the schema walks every relation the large schema adds, three for each relation of the small
 * one, for each query the second program adds.
 */
const queries = sources
const small = 2 * queries
const large = 4 * small

/** The four programs of one combinator, in order: `queries` and twice as many queries, over each schema. */
const combinatorShapes = [
	{ relations: small, queries },
	{ relations: small, queries: 2 * queries },
	{ relations: large, queries },
	{ relations: large, queries: 2 * queries }
] as const

/** How a combinator prints. */
export const combinatorName = (combinator: Combinator): string => `queries built by ${combinator}`

/**
 * The cost of one combinator's queries, measured: its four programs typecheck with no diagnostic, and the queries the
 * second program adds cost exactly as many instantiations over the large schema as over the small one.
 */
export const combinatorCost = (at: Measuring, combinator: Combinator) =>
	Effect.gen(function* () {
		const measured = yield* measuredEach(
			at,
			Arr.map(combinatorShapes, (shape) => ({
				size: shape.relations,
				source: (entries: PreludeAt) => combinatorProgram({ ...shape, combinator }, entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, combinatorName(combinator))
		}
		const count = (i: number): number =>
			defined(measured[i], `the program of ${combinator} at ${i}`).instantiations
		const added = { small: count(1) - count(0), large: count(3) - count(2) }
		assert.equal(
			added.large,
			added.small,
			`the last ${queries} queries built by ${combinator} cost ${added.large} instantiations over ${large} relations and ${added.small} over ${small}`
		)
	})
