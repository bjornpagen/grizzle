import { assert, defined } from "@bjornpagen/testing/assert"
import { Array as Arr, Effect } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { assertClean, type Measuring, measuredEach } from "#test/types/batch/measured.ts"

/**
 * The plain-query programs (plain.test.ts): queries that attach nothing, each one rule over P of a schema of three
 * relations, a union of two such rules, or a union of sixteen, each arm's head with a constant of its own as a union of
 * grading's values is (edullm's ledger, grade.ts), written `queries` times, the program checked at two sizes. A query's
 * attachments are a phantom of its type (types/query/query.ts At, Attachment), which a query that attaches nothing holds
 * as one alias, and a union holds as the query's it was built on; what an added query costs is the cost a program pays
 * for each query it writes, which the gate holds to its measured bound.
 */
export type PlainShape = "one rule" | "union of two rules" | "union of sixteen rules"

/** The cells of plainQueries, minted as a dictionary in its door (test/types/query/budget/plain.dictionary.ts). */
export const plainShapesItems: readonly [PlainShape, ...ReadonlyArray<PlainShape>] = [
	"one rule",
	"union of two rules",
	"union of sixteen rules"
]

/** The arms of the widest union a plain query is measured at. */
const sixteen = 16

/** An arm whose head holds a constant of its own at k, the j-th, as each arm of a union of grading's values does. */
const keyedArm = (scope: string, j: number): string =>
	`(r) => {\n\tconst { id, n } = v(P, "${scope}")\n\treturn r.match(P, { id, n }).find({ id, n, k: "k${j}" })\n}`

/** One query of a shape, named q<i>. */
const queryOf = (shape: PlainShape, i: number): string => {
	const arm = (scope: string) =>
		`(r) => {\n\tconst { id, n } = v(P, "${scope}")\n\treturn r.match(P, { id, n }).find({ id, n })\n}`
	switch (shape) {
		case "one rule":
			return `export const q${i} = query(S).rule(${arm("p")})\n`
		case "union of two rules":
			return `export const q${i} = query(S).rule(${arm("p")}).rule(${arm("q")})\n`
		case "union of sixteen rules":
			return `export const q${i} = query(S)${Arr.join(
				Arr.map(indices(sixteen), (j) => `.rule(${keyedArm(`s${j}`, j)})`),
				""
			)}\n`
	}
}

/** The program of `queries` queries of a shape, its imports read through the gates' prelude as `entries` reaches it. */
const plainProgram = (shape: PlainShape, queries: number, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/query/budget/plain.ts at ${jsonText({ shape, queries })}.`,
		entries,
		`export const P = relation("P", { id: Id, n: pg.integer }, ["id"])
export const C = relation("C", { p: Id, k: pg.integer, w: pg.integer }, ["p", "k"])
export const D = relation("D", { p: Id, k: pg.integer, w: pg.integer }, ["p", "k"])
export const S = schema("S", [P, C, D], [contained(on(C, "p"), on(P, "id")), contained(on(D, "p"), on(P, "id"))])
${Arr.join(
	Arr.map(indices(queries), (i) => queryOf(shape, i)),
	""
)}`
	)

/** The queries of the smaller program; the larger writes twice as many, so the step adds `step` queries. */
const step = 20

/**
 * What one query of each shape adds to a program's instantiations, at most: what it added when the attachments phantom
 * was cut, a one-rule query four more than before the phantom; and since lane PERF-TYPES's cuts, what each costs now
 * that every member of a query reads its schema off its phantom (types/query/query.ts OverSchema), a union's arm check
 * infers nothing (NoInfer), a rule's evidence is held where it is inferred to its keys and card alone
 * (types/evidence/evidence.ts InferredEvidence), its head origins read where they are read, and a union's further arm is
 * judged beside the arms' carriers read off their union at once, attachments and key sets first, each field's carriers
 * once (ArmsMeet), and a rule's keys read each key's needs and the head's terms once (types/evidence/evidence.ts
 * NeedsOfKeys, HeadEntries): a one-rule query 1,452, a union of two rules 3,879, a union of sixteen rules 53,464.
 *
 * @limitKind measured
 * @owner the query facade's type cost gates (test/types/query/budget/plain.ts)
 * @unit instantiations a query adds
 * @scope one query of the shape, checked by one checker against the engine's and the shell's declarations, as
 *   test/types/batch/measured.ts checks a program
 * @evidence ~/.cache/grizzle-release/RECORDS-ATTACH-tools/pin (write.ts writes this module's program through the
 *   gates' prelude, run.sh checks it at 20 and 40 queries as measured.ts checks a program: tsgo --checkers 1
 *   --extendedDiagnostics, referencing packages/engine and packages/grizzle) and its runs
 *   RECORDS-ATTACH-pin-{lanebase,lane,lanekill}.log: before the phantom, with it, and with `At | At2`; the same
 *   run.sh over lane PERF-TYPES's workspace (~/.cache/grizzle/perf-types) with its cut and with `At | At2` over it
 * @observed 2026-11-21, 11:50 to 12:15 UTC; the union's bound again 2026-11-21, 16:3x UTC
 * @environment cassowary, Ubuntu 26.04 arm64, 64 cores, load 60 to 90 from other sessions; Node 26.13.1, TypeScript
 *   7.1.0-beta (tsgo); grizzle at pin-stack 20760a35f (the records cars) and the attachments cut over it; the union's
 *   bound at hub main 71af69764 and lane PERF-TYPES's cut over it, load 400 to 500
 * @workload a schema of three relations; 20 and 40 one-rule queries over one of them, 20 and 40 unions of two such
 *   rules, and 20 and 40 unions of sixteen, each arm's head with a constant of its own, each program checked alone
 * @result per added query, one rule: 2,372 instantiations before the phantom, 2,376 with it; a union of two rules:
 *   5,843 before, 5,848 with the union keeping its receiver's attachments, 5,864 with a union holding both arms'
 *   (`At | At2`); after PERF-TYPES's first cut, 5,826, and 5,842 with `At | At2`; after its second, one rule 1,534, and
 *   2,399 with the first rule's evidence held to Evidence whole, a union of two rules 4,142, and 4,158 with
 *   `At | At2`; after its third, a union of two rules 4,022, and 4,038 with `At | At2`, and a union of sixteen rules
 *   60,694 (70,807 before it, 69,491 with every arm's attachment read beside each arm before it); after its fourth, a
 *   further arm met beside each carrier the arms before it deliver at a field, a union of sixteen rules 55,160 (58,474
 *   with each arm before it met apart, Mismatched pairwise) and a union of two rules 4,043, 21 more than the third left
 *   it, the price of reading a field's carriers once, and 4,059 with `At | At2`; after its fifth, a rule's keys read each key's needs and the head's terms once, one rule 1,452,
 *   a union of two rules 3,879, a union of sixteen rules 53,464; every program clean; types are not read
 *   (the checker interns them)
 * @decision the bound is the cut's own cost, exactly: a change that makes a query that attaches nothing pay more for
 *   its type's attachments, or any other cost per plain query, is refused here, and a change that lowers it lowers the
 *   bound
 * @revalidate a TypeScript 7 or tsgo upgrade; another machine; any change to the query facade's types
 *   (types/query/query.ts, types/query/rule.ts, the evidence) that moves a plain query's cost, which states its cost here
 */
const addedAtMost: { readonly [S in PlainShape]: number } = {
	"one rule": 1452,
	"union of two rules": 3879,
	"union of sixteen rules": 53464
}

/** How a shape prints. */
export const plainShapeName = (shape: PlainShape): string => `queries of ${shape}`

/**
 * The cost of a shape's queries, measured: both programs typecheck with no diagnostic, and the queries the larger adds
 * cost no more, each, than the shape's bound.
 */
export const plainCost = (at: Measuring, shape: PlainShape) =>
	Effect.gen(function* () {
		const measured = yield* measuredEach(
			at,
			Arr.map([step, 2 * step], (queries) => ({
				size: queries,
				source: (entries: PreludeAt) => plainProgram(shape, queries, entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, plainShapeName(shape))
		}
		const count = (i: number): number =>
			defined(measured[i], `the program of ${shape} at ${i}`).instantiations
		const added = (count(1) - count(0)) / step
		assert.ok(
			added <= addedAtMost[shape],
			`a query of ${shape} adds ${added} instantiations, more than ${addedAtMost[shape]}`
		)
	})
