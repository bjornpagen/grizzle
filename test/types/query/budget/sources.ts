import { indices } from "@bjornpagen/grizzle-text/base/array"
import { assert, defined } from "@bjornpagen/testing/assert"
import { Array as Arr, Effect } from "effect"
import { jsonText } from "#compiler/core/trusted.ts"
import { type PreludeAt, preludeProgram } from "#test/support/prelude.ts"
import { assertClean, type Measuring, measuredEach } from "#test/support/types/batch/measured.ts"

/**
 * The matched-source programs, one per kind of source a rule matches (sources.test.ts), each written over a schema of
 * `relations` relations R0 … of three fields, an id, a package and a kind, keyed by the id, beside a roster C, with
 * `rules` queries each of one rule matching a source of the kind: a relation, the roster, a closed relation over it, a
 * query over the schema, or a derived relation over such a query, declared in an extension of the schema. The sources are the first `sources` of
 * their kind, every program's, each a query's or a derived relation's over its relation, and the rules match them in
 * turn, so every source is matched in every program and the rules a program adds over another match sources matched
 * already: each added rule costs its match alone, never what a source's first use reads once, its definition's
 * evidence. As pantry's LOM level matches its vocabulary's queries (lom.ts PackageFact), rule after rule, over a
 * schema of hundreds of relations.
 */
type SourceShape = {
	readonly relations: number
	readonly rules: number
	readonly kind: SourceKind
}

/** A kind of source a rule matches, each a case of the gate. */
export type SourceKind = "relation" | "roster" | "closed" | "query" | "derived"

/** The cells of matchedSources, minted as a dictionary in its door (test/types/query/budget/sources.dictionary.ts). */
export const sourceKindsItems: readonly [SourceKind, ...ReadonlyArray<SourceKind>] = [
	"relation",
	"roster",
	"closed",
	"query",
	"derived"
]

/** The sources of a kind every program declares and matches, its rules each matching one in turn. */
const sources = 5

/** The source rule i matches: the (i mod sources)-th of its kind. */
const sourceOf = (kind: SourceKind, i: number): string => {
	const j = i % sources
	switch (kind) {
		case "relation":
			return `R${j}`
		case "roster":
			return "C"
		case "closed":
			return `K${j}`
		case "query":
			return `q${j}`
		case "derived":
			return `D${j}`
	}
}

/** Query j, over relation j, every field of it in its head; and, matching derived relations, the derived relation of it. */
const sourceDefinitions = (kind: SourceKind): string => {
	switch (kind) {
		case "relation":
		case "roster":
			return ""
		case "closed":
			return ""
		case "query":
		case "derived":
			return Arr.join(
				Arr.map(
					indices(sources),
					(j) => `export const q${j} = query(S).rule((r) => {
	const { id, package: pkg, kind } = v(R${j}, "x")
	return r.match(R${j}, { id, package: pkg, kind }).find({ id, package: pkg, kind })
})
${kind === "derived" ? `export const D${j} = derived("D${j}", q${j})\n` : ""}`
				),
				""
			)
	}
}

/** The closed relations over C a program of closed sources declares in S: K0 … keyed by C's id, none for any other kind. */
const closedRelations = (kind: SourceKind): ReadonlyArray<string> =>
	kind === "closed" ? Arr.map(indices(sources), (j) => `K${j}`) : []

/** The schema the rules are over: S, or for derived sources the extension E that declares them. */
const ruleSchema = (kind: SourceKind): string => (kind === "derived" ? "E" : "S")

/** A complete program at `shape`, its imports read through the gates' prelude as `entries` reaches it. */
const sourceProgram = (shape: SourceShape, entries: PreludeAt): string =>
	preludeProgram(
		`// Generated by test/types/query/budget/sources.ts at ${jsonText(shape)}.`,
		entries,
		`export const Kind = str.regex("^[a-z]{1,8}$")
export const C = closed.ordered("C", ["a", "b"])
${Arr.join(
	Arr.map(
		indices(shape.relations),
		(i) => `export const R${i} = relation("R${i}", { id: Id, package: Id, kind: Kind }, ["id"])\n`
	),
	""
)}${Arr.join(
			Arr.map(
				closedRelations(shape.kind),
				(k) =>
					`export const ${k} = closed.relation("${k}", { id: closedId(C), kind: Kind }, ["id"], [{ id: "a", kind: "a" }])\n`
			),
			""
		)}export const S = schema("S", [C, ${Arr.join(
			[...Arr.map(indices(shape.relations), (i) => `R${i}`), ...closedRelations(shape.kind)],
			", "
		)}], [])
${sourceDefinitions(shape.kind)}${
			shape.kind === "derived"
				? `export const E = schema.extend([S], "E", [${Arr.join(
						Arr.map(indices(sources), (j) => `D${j}`),
						", "
					)}], [])\n`
				: ""
		}${Arr.join(
			Arr.map(
				indices(shape.rules),
				(i) => `export const U${i} = query(${ruleSchema(shape.kind)}).rule((r) => {
	const { id } = v(${sourceOf(shape.kind, i)}, "s")
	return r.match(${sourceOf(shape.kind, i)}, { id }).find({ id })
})
`
			),
			""
		)}`
	)

/**
 * The rules of the first program, and the schemas' sizes. The second program writes twice as many rules, so the small
 * schema holds as many relations as it has rules; the large one holds four times as many, so a match that walks the
 * schema walks every relation the large schema adds, three for each relation of the small one, for each rule the second
 * program adds.
 */
const rules = sources
const small = 2 * rules
const large = 4 * small

/** The four programs of one kind, in order: `rules` and twice as many rules, over each schema. */
const sourceShapes = [
	{ relations: small, rules },
	{ relations: small, rules: 2 * rules },
	{ relations: large, rules },
	{ relations: large, rules: 2 * rules }
] as const

/** How a kind prints. */
export const sourceKindName = (kind: SourceKind): string => `matches of a ${kind}`

/**
 * The cost of one kind's matches, measured: its four programs typecheck with no diagnostic, and the rules the second
 * program adds cost exactly as many instantiations over the large schema as over the small one.
 */
export const matchCost = (at: Measuring, kind: SourceKind) =>
	Effect.gen(function* () {
		const measured = yield* measuredEach(
			at,
			Arr.map(sourceShapes, (shape) => ({
				size: shape.relations,
				source: (entries: PreludeAt) => sourceProgram({ ...shape, kind }, entries)
			}))
		)
		for (const m of measured) {
			assertClean(m, sourceKindName(kind))
		}
		const count = (i: number): number =>
			defined(measured[i], `the program of ${kind} matches at ${i}`).instantiations
		const added = { small: count(1) - count(0), large: count(3) - count(2) }
		assert.equal(
			added.large,
			added.small,
			`the last ${rules} rules matching a ${kind} cost ${added.large} instantiations over ${large} relations and ${added.small} over ${small}`
		)
	})
