import { Array as Arr, Effect } from "effect"
import { served } from "#adapter/public/layer.ts"
import type { AnyLogin } from "#compiler/public/schema.ts"
import {
	Bare,
	Clocked,
	Defers,
	Keys,
	Mixed,
	Pages,
	Reads,
	Writes,
	WritesTwice
} from "#test/support/agreement/decoder-logins.ts"
import { compiledServedFile } from "#test/support/compiled-served.ts"
import { type PreludeAt, preludeAt, preludeFrom, preludeProgram } from "#test/support/prelude.ts"

/**
 * The decoder agreement: the type of a served login's `decoder` (adapter/types/layer.ts DecoderOf, by its login's
 * ReadsOf, the decision LiveOf reads) against the decoder its real served file names. The oracle is the runtime: each
 * login of the box (test/support/agreement/decoder-logins.ts) is compiled with no database as `grizzle generate`
 * compiles it (compiled-served.ts compiledServedFile) and served (adapter/served/served.ts served), and its decoder's
 * kind read off the value. The one program the type tier checks (test/types/api/decoder.test.ts) states, for each
 * login, that ServedLogin<typeof L>["decoder"] is exactly the arm its file holds, NoDecoder or DecoderLogin, and for
 * each login whose file names a decoder login, that roleNameOf takes it with no narrowing; and that a served login of
 * AnyLogin, whose type cannot tell, is typed with every arm the box's files hold.
 */
const box = [
	["Bare", Bare],
	["Writes", Writes],
	["WritesTwice", WritesTwice],
	["Clocked", Clocked],
	["Reads", Reads],
	["Pages", Pages],
	["Keys", Keys],
	["Defers", Defers],
	["Mixed", Mixed]
] as const satisfies ReadonlyArray<readonly [string, AnyLogin]>

/** The public type of each arm of a served decoder, by the kind its value holds. */
const armOf = { none: "NoDecoder", decoderLogin: "DecoderLogin" } as const

/** Each login of the box, by its binding, with the arm of the decoder its real served file names. */
const decoders = (): ReadonlyArray<readonly [string, keyof typeof armOf]> =>
	Arr.map(
		box,
		([binding, value]) =>
			[binding, served<AnyLogin>(compiledServedFile(value), value.name).decoder.kind] as const
	)

/** The decoder program's prelude (test/support/programs/decoder.ts), every repository name it reads. */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/decoder.ts"))

/** The program's prelude as its directory reaches it, `entry` spelling a repository path from there. */
export const decoderEntriesFrom = (entry: (path: string) => string): PreludeAt =>
	preludeFrom(prelude, entry)

/** The program: each login's decoder typed as the arm its file holds, and AnyLogin's as every arm the box holds. */
export const decoderModule = (entries: PreludeAt): string => {
	const read = decoders()
	const arms = Arr.dedupe(Arr.map(read, ([, kind]) => armOf[kind]))
	return preludeProgram(
		"// Generated by test/types/api/decoder.ts: each served login's decoder type against the decoder its file names.",
		entries,
		Arr.join(
			[
				"type Equals<A, B> = (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false",
				"type Expect<T extends true> = T",
				"",
				...Arr.flatMap(read, ([binding, kind]) => [
					`export type d_${binding} = Expect<Equals<ServedLogin<typeof ${binding}>["decoder"], ${armOf[kind]}>>`,
					...(kind === "decoderLogin"
						? [
								`export const r_${binding} = (login: ServedLogin<typeof ${binding}>): string => roleNameOf(login.decoder, {})`
							]
						: [])
				]),
				`export type d_AnyLogin = Expect<Equals<ServedLogin<AnyLogin>["decoder"], ${Arr.join(arms, " | ")}>>`,
				""
			],
			"\n"
		)
	)
}
