import { Array as Arr, Effect } from "effect"
import { served } from "#adapter/public/layer.ts"
import type { AnyLogin } from "#compiler/public/schema.ts"
import {
	Answered,
	AnsweredBeside,
	AnsweredKeys,
	AnsweredPages,
	Bare,
	Clocked,
	Keys,
	Mixed,
	Pages,
	Reads,
	Writes,
	WritesTwice
} from "#test/support/agreement/decoder-logins.ts"
import { compiledServedFile } from "#test/support/compiled-served.ts"
import { preludeAt, preludeFrom, preludeModule } from "#test/support/prelude.ts"
import { batchOwned, caseOwned, type Entry, type Program } from "#test/types/batch/batch.ts"

/**
 * The decoder agreement: the type of a served login's `decoder` (adapter/types/layer.ts DecoderOf, by its login's
 * ReadsOf, the decision LiveOf reads) against the decoder its real served file names. The oracle is the runtime: each
 * login of the box (test/support/agreement/decoder-logins.ts) is compiled with no database as `grizzle generate`
 * compiles it (compiled-served.ts compiledServedFile) and served (adapter/served/served.ts served), and its decoder's
 * kind read off the value. The one program the type tier checks (test/types/api/decoder.test.ts) states, for each
 * login, that ServedLogin<typeof L>["decoder"] is exactly the arm its file holds, NoDecoder or DecoderLogin, and that
 * DbLayer.make of L requires a live source (LiveOf) exactly where its file names a decoder login, so a login whose reads
 * are all answered opens with none; for each login whose file names a decoder login, that roleNameOf takes it with no
 * narrowing; and that a served login of AnyLogin, whose type cannot tell, is typed with every arm the box's files hold.
 */
const box = [
	["Bare", Bare],
	["Writes", Writes],
	["WritesTwice", WritesTwice],
	["Clocked", Clocked],
	["Reads", Reads],
	["Pages", Pages],
	["Keys", Keys],
	["Mixed", Mixed],
	["Answered", Answered],
	["AnsweredPages", AnsweredPages],
	["AnsweredKeys", AnsweredKeys],
	["AnsweredBeside", AnsweredBeside]
] as const satisfies ReadonlyArray<readonly [string, AnyLogin]>

/** The public type of each arm of a served decoder, by the kind its value holds. */
const armOf = { none: "NoDecoder", decoderLogin: "DecoderLogin" } as const

/** The arm of the decoder a login's real served file names. */
const decoderOf = (value: AnyLogin): keyof typeof armOf =>
	served<AnyLogin>(compiledServedFile(value), value.name).decoder.kind

/** A cell of the box: one login of it, by its binding, or AnyLogin, whose decoder's type must be every arm. */
type DecoderCell =
	| Readonly<{ kind: "login"; binding: (typeof box)[number][0]; value: AnyLogin }>
	| Readonly<{ kind: "any" }>

/** The cells of decoderBox, minted as a dictionary in its door (test/types/api/decoder.dictionary.ts). */
export const decoderBoxItems: Arr.NonEmptyReadonlyArray<DecoderCell> = [
	...Arr.map(box, ([binding, value]): DecoderCell => ({ kind: "login", binding, value })),
	{ kind: "any" }
]

/** The decoder program's prelude (test/support/programs/decoder.ts), every repository name it reads. */
const prelude = await Effect.runPromise(preludeAt("test/support/programs/decoder.ts"))

/** A cell's lines: a login's decoder typed as the arm its file holds, AnyLogin's as every arm the box's files hold. */
const cellLines = (cell: DecoderCell): ReadonlyArray<string> => {
	switch (cell.kind) {
		case "login": {
			const kind = decoderOf(cell.value)
			return [
				`export type d_${cell.binding} = Expect<Equals<ServedLogin<typeof ${cell.binding}>["decoder"], ${armOf[kind]}>>`,
				`export type l_${cell.binding} = Expect<Equals<[LiveOf<typeof ${cell.binding}>] extends [never] ? "none" : "decoderLogin", "${kind}">>`,
				...(kind === "decoderLogin"
					? [
							`export const r_${cell.binding} = (login: ServedLogin<typeof ${cell.binding}>): string => roleNameOf(login.decoder, {})`
						]
					: [])
			]
		}
		case "any": {
			const arms = Arr.dedupe(Arr.map(box, ([, value]) => armOf[decoderOf(value)]))
			return [
				`export type d_AnyLogin = Expect<Equals<ServedLogin<AnyLogin>["decoder"], ${Arr.join(arms, " | ")}>>`
			]
		}
	}
}

/** The program over a batch's cells, each a line or two of its own. */
export const decoderProgram = (
	cells: Arr.NonEmptyReadonlyArray<DecoderCell>,
	entry: Entry
): Program => [
	preludeModule(
		"index.ts",
		"// Generated by test/types/api/decoder.ts: each served login's decoder type against the decoder its file names.",
		preludeFrom(prelude, entry),
		[
			{
				owner: batchOwned,
				lines: [
					"export type Equals<A, B> = (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false",
					"export type Expect<T extends true> = T",
					""
				]
			},
			...Arr.map(cells, (cell, at) => ({ owner: caseOwned(at), lines: cellLines(cell) }))
		]
	)
]
