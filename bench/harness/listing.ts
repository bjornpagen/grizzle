import { Array as Arr, pipe, String as Str } from "effect"
import type { GateOutcome } from "#bench/harness/gate.ts"
import { firstSentence, type GateId, type GateOwner, gateCatalog } from "#bench/harness/rules.ts"
import { outcomeOver, type RecordedGate, recordedVerdicts } from "#bench/harness/runner.ts"

/**
 * The gate listing, bench/results/GATES.md: every gate of the catalog (R01-R42 and the rest) has a bench file and a
 * recorded verdict, and the listing shows which are not yet completed.
 *
 * The listing names every gate of the catalog (R01 to R42, the queue claim and the refresh lifetime) with the bench
 * files that cover it and how far it has come:
 * - `not yet built`: no bench file covers it;
 * - `complete`: a full-scale record on disk of a file that covers it passed it;
 * - `quick-only`: a bench file covers it, but no full-scale record has passed it: it has run at quick scale only, or
 *   not on this machine, or its full-scale verdict is not a pass, which the listing says.
 * Each row carries the worst recorded verdict at the larger scale recorded, and why a gate that is not complete is not.
 * Records are read from bench/results/gates (runner.ts readRecords); a quick record proves a gate runs end to end and
 * records a well-formed verdict, never that it holds at the gate's load. `pnpm bench:full` writes the listing.
 */
export const listedStatuses = ["complete", "quick-only", "not yet built"] as const

type ListedStatus = (typeof listedStatuses)[number]

export interface CoveringFile {
	readonly file: string
	readonly gates: ReadonlyArray<GateId>
}

interface Listed {
	readonly gate: GateId
	readonly title: string
	readonly owner: GateOwner
	readonly files: ReadonlyArray<string>
	/** The worst verdict over the covering files' records at the larger scale recorded, or `missing`. */
	readonly outcome: GateOutcome
	readonly scale: "full" | "quick" | "none"
}

export type ListedGate =
	| (Listed & { readonly status: "complete" })
	| (Listed & { readonly status: "quick-only" | "not yet built"; readonly why: string })

/** Every gate of the catalog with its files, status and worst recorded verdict. */
export const gateListing = (
	files: ReadonlyArray<CoveringFile>,
	records: ReadonlyArray<RecordedGate>
): ReadonlyArray<ListedGate> =>
	Arr.map(gateCatalog, (entry): ListedGate => {
		const covering = Arr.map(
			Arr.filter(files, (f) => f.gates.includes(entry.id)),
			(f) => f.file
		)
		const own = Arr.filter(records, (r) => covering.includes(r.file) && r.gates.includes(entry.id))
		const full = Arr.filter(own, (r) => !r.quick)
		const scale = full.length > 0 ? "full" : own.length > 0 ? "quick" : "none"
		const latest = Arr.flatMap(full.length > 0 ? full : own, (r) => recordedVerdicts(r, entry.id))
		const outcome = outcomeOver(Arr.map(latest, (v) => v.outcome))
		const base = {
			gate: entry.id,
			title: entry.title,
			owner: entry.owner,
			files: covering,
			outcome,
			scale
		} as const
		if (covering.length === 0) {
			return { ...base, status: "not yet built", why: "No bench file covers it yet." }
		}
		if (scale === "full" && outcome === "pass") {
			return { ...base, status: "complete" }
		}
		const reasons = Arr.flatMap(latest, (v) =>
			v.outcome === "pass" ? [] : [firstSentence(v.reason)]
		)
		const why =
			scale === "none"
				? "Built; no record on this machine yet."
				: scale === "quick"
					? `Built and run at quick scale only (${outcome}); the full-scale run is pending.`
					: `Its full-scale verdict is ${outcome}.`
		return { ...base, status: "quick-only", why: Arr.join([why, ...reasons], " ") }
	})

const cell = (text: string): string =>
	pipe(Str.replaceAll("|", "\\|")(text), Str.replaceAll("\n", " "))

/** The listing as bench/results/GATES.md. */
export const renderGateListing = (listing: ReadonlyArray<ListedGate>): string => {
	const count = (status: ListedStatus) => Arr.filter(listing, (g) => g.status === status).length
	const lines = [
		"# Performance gates",
		"",
		"Generated by `pnpm bench:full` from the bench files under `bench/query`, `bench/write` and `bench/queue` and the records in `bench/results/gates/`. Every gate is listed: R01 to R42, the compiler's performance rules, then the work-queue claim and the refresh lifetime (bench/harness/rules.ts). A gate is `complete` when a full-scale record passed it, `quick-only` when its bench file exists but no full-scale record has passed it, and `not yet built` when no bench file covers it. Every gate that is not `complete` is not yet completed. `pnpm bench` measures on the local cluster, whose timings are information and never decide a verdict.",
		"",
		`Gates: ${listing.length}. ${Arr.join(
			Arr.map(listedStatuses, (s) => `${s}: ${count(s)}`),
			". "
		)}.`,
		"",
		"| Gate | Rule | Owner | Bench files | Status | Latest verdict | Why not complete |",
		"| --- | --- | --- | --- | --- | --- | --- |"
	]
	for (const g of listing) {
		lines.push(
			`| ${g.gate} | ${cell(g.title)} | ${g.owner} | ${Arr.match(g.files, {
				onEmpty: () => "-",
				onNonEmpty: (fs) =>
					Arr.join(
						Arr.map(fs, (f) => `\`${f}\``),
						", "
					)
			})} | ${g.status} | ${
				g.scale === "none" ? "-" : `${g.outcome} (${g.scale})`
			} | ${g.status === "complete" ? "-" : cell(g.why)} |`
		)
	}
	return `${Arr.join(lines, "\n")}\n`
}
