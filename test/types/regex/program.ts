import { Array as Arr } from "effect"
import type { BudgetEntries } from "#test/types/query/budget/generate.ts"
import { rows } from "#test/types/regex/matrix.ts"
import { literal } from "#test/types/regex/schema.ts"

/**
 * The generated program over the inference matrix (test/types/regex/matrix.ts): per row, the str.regex call, the
 * members assigned to the host type and the outside values refused by it, and, where the scan widens, the exact
 * assertion that the host type is string. Each refusal is under a directive, `// @ts-expect-error -- TSnnnn: why` or
 * `// @ts-expect-error -- TSnnnn refusal: <message>`. An outside value is refused with TS2322; where the checker's
 * heuristic suggests a member instead it raises TS2820, which matrix.test.ts reads as the same refusal. The type-test
 * batch (test/types/batch) checks it armed and disarmed; matrix.test.ts reads both.
 *
 * The generated program over the matrix: one block per row.
 */
export const programSource = (entries: BudgetEntries): string => {
	const lines = [
		"// Generated by test/types/regex/program.ts from matrix.ts.",
		`import { str } from ${literal(entries.text)}`,
		`import type { Infer } from ${literal(entries.fields)}`,
		"",
		"type Equals<A, B> = (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false",
		"type Expect<T extends true> = T",
		""
	]
	for (const [i, row] of rows.entries()) {
		const name = `m${i}`
		lines.push(`// ${row.name}`)
		const call = row.call
		if (call.kind === "declared") {
			lines.push(...call.declarations(`${name}_`))
		}
		if (row.host.kind === "refused") {
			lines.push(`// @ts-expect-error -- ${row.host.refused}: ${row.host.reason}`)
		}
		const args =
			call.kind === "literal"
				? `${literal(row.source)}, ${literal(row.flags)}`
				: call.args(`${name}_`)
		lines.push(`export const ${name} = str.regex(${args})`)
		if (row.host.kind === "widened") {
			lines.push(`export type ${name}_host = Expect<Equals<Infer<typeof ${name}>, string>>`)
		}
		for (const [j, member] of row.members.entries()) {
			lines.push(`export const ${name}_member${j}: Infer<typeof ${name}> = ${literal(member)}`)
		}
		for (const [j, outside] of row.outside.entries()) {
			const value = literal(outside)
			lines.push(`// @ts-expect-error -- TS2322: ${value} lies outside the host type`)
			lines.push(`export const ${name}_outside${j}: Infer<typeof ${name}> = ${value}`)
		}
		lines.push("")
	}
	return Arr.join(lines, "\n")
}
